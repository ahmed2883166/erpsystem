"""Explicit SQL execution adapter for the supported database drivers.

Only positional qmark placeholders outside SQL literals/comments are translated
for psycopg. This is deliberately opt-in; it is not a general SQL dialect
translator.
"""
import re

from db_compat import database_dialect


_POSTGRES_IDENTITY_DDL = re.compile(
    r"(\bCREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[^ (]+\s*\([^;]*?)(\bid\s+)INTEGER(\s+PRIMARY\s+KEY\b)(?:\s+AUTOINCREMENT\b)?",
    re.IGNORECASE | re.DOTALL,
)


def adapt_sql_for_postgresql(sql):
    """Adapt the narrow SQLite DDL pattern used by NEXUS schema initializers.

    Only an inline single-column id INTEGER PRIMARY KEY declaration inside
    CREATE TABLE is changed. Existing IDs remain valid; PostgreSQL generates
    new IDs with an identity sequence. Other SQL is deliberately untouched.
    """
    if not isinstance(sql, str):
        raise TypeError("SQL statement must be a string")
    adapted = _POSTGRES_IDENTITY_DDL.sub(
        lambda match: match.group(1) + match.group(2)
        + "BIGINT GENERATED BY DEFAULT AS IDENTITY" + match.group(3),
        sql,
        count=1,
    )
    # SQLite accepts CURRENT_TIMESTAMP as the default for TEXT columns.
    # PostgreSQL requires the timestamp expression to be explicitly cast
    # when the declared column remains TEXT (as existing ERP modules expect).
    adapted = re.sub(
        r"(\\b[A-Za-z_][A-Za-z0-9_]*\\s+TEXT\\b[^,\\n]*?\\bDEFAULT\\s+)CURRENT_TIMESTAMP\\b",
        r"\\1(CURRENT_TIMESTAMP::text)",
        adapted,
        flags=re.IGNORECASE,
    )
    return adapted


def qmark_to_format(sql):
    """Translate SQL qmark bind markers to psycopg %s markers.

    Quoted strings/identifiers, line comments, nested block comments, and
    PostgreSQL dollar-quoted strings are preserved. This helper is intended
    only for statements whose unquoted question marks are bind markers.
    PostgreSQL uses %s placeholders, so a doubled question mark in source SQL
    is reduced to the literal JSON operator before execution.
    """
    if not isinstance(sql, str):
        raise TypeError("SQL statement must be a string")

    out = []
    i = 0
    length = len(sql)
    state = "normal"
    block_depth = 0
    dollar_tag = None

    while i < length:
        char = sql[i]
        nxt = sql[i + 1] if i + 1 < length else ""

        if state == "normal":
            if char == "'":
                previous_is_e = (
                    i > 0 and sql[i - 1] in "eE"
                    and (i < 2 or not (sql[i - 2].isalnum() or sql[i - 2] == "_"))
                )
                state = "escape_single" if previous_is_e else "single"
                out.append(char)
                i += 1
                continue
            if char == '"':
                state = "double"
                out.append(char)
                i += 1
                continue
            if char == "-" and nxt == "-":
                state = "line_comment"
                out.extend((char, nxt))
                i += 2
                continue
            if char == "/" and nxt == "*":
                state = "block_comment"
                block_depth = 1
                out.extend((char, nxt))
                i += 2
                continue
            if char == "$" and (i == 0 or not (sql[i - 1].isalnum() or sql[i - 1] in "_$")):
                end = sql.find("$", i + 1)
                if end != -1:
                    tag_body = sql[i + 1:end]
                    if tag_body == "" or (
                        tag_body[0].isalpha() or tag_body[0] == "_"
                    ) and all(c.isalnum() or c == "_" for c in tag_body):
                        dollar_tag = sql[i:end + 1]
                        state = "dollar"
                        out.append(dollar_tag)
                        i = end + 1
                        continue
            if char == "?" and nxt == "?":
                # The doubled form is an escape used only in source SQL so
                # this qmark adapter can distinguish a literal JSON operator
                # from a positional bind marker. psycopg receives one operator.
                out.append("?")
                i += 2
                continue
            if char == "?":
                out.append("%s")
            else:
                out.append(char)
            i += 1
            continue

        if state in {"single", "escape_single"}:
            out.append(char)
            if char == "'" and nxt == "'":
                out.append(nxt)
                i += 2
                continue
            if state == "escape_single" and char == "\\" and nxt:
                out.append(nxt)
                i += 2
                continue
            if char == "'":
                state = "normal"
            i += 1
            continue

        if state == "double":
            out.append(char)
            if char == '"' and nxt == '"':
                out.append(nxt)
                i += 2
                continue
            if char == '"':
                state = "normal"
            i += 1
            continue

        if state == "line_comment":
            out.append(char)
            if char == "\n":
                state = "normal"
            i += 1
            continue

        if state == "block_comment":
            if char == "/" and nxt == "*":
                block_depth += 1
                out.extend((char, nxt))
                i += 2
                continue
            if char == "*" and nxt == "/":
                block_depth -= 1
                out.extend((char, nxt))
                i += 2
                if block_depth == 0:
                    state = "normal"
                continue
            out.append(char)
            i += 1
            continue

        if state == "dollar":
            if sql.startswith(dollar_tag, i):
                out.append(dollar_tag)
                i += len(dollar_tag)
                dollar_tag = None
                state = "normal"
                continue
            out.append(char)
            i += 1
            continue

    if state in {"single", "escape_single", "double", "block_comment", "dollar"}:
        raise ValueError(f"Unterminated SQL construct while translating placeholders: {state}.")
    return "".join(out)


def execute_compat(connection, sql, params=()):
    """Execute a qmark-parameterized statement on SQLite or psycopg 3.

    The caller owns transaction boundaries and must supply positional values.
    """
    dialect = database_dialect(connection)
    if dialect == "sqlite":
        return connection.execute(sql, params)
    return connection.execute(qmark_to_format(adapt_sql_for_postgresql(sql)), params)



def executemany_compat(connection, sql, seq_of_params):
    """Execute a qmark-parameterized batch on SQLite or psycopg 3.

    This helper does not commit; the caller owns the transaction.
    """
    dialect = database_dialect(connection)
    if dialect == "sqlite":
        return connection.executemany(sql, seq_of_params)
    statement = qmark_to_format(adapt_sql_for_postgresql(sql))
    cursor = connection.cursor()
    cursor.executemany(statement, seq_of_params)
    return cursor
