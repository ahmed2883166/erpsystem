"""Tests for explicit generated-ID insertion across supported drivers."""
import os
import sqlite3
import unittest

from db_insert import insert_one_returning_id


class SQLiteGeneratedIdTests(unittest.TestCase):
    def test_returns_generated_integer_primary_key_without_committing(self):
        connection = sqlite3.connect(":memory:")
        try:
            connection.execute(
                "CREATE TABLE insert_probe (id INTEGER PRIMARY KEY, label TEXT)"
            )
            generated_id = insert_one_returning_id(
                connection,
                "INSERT INTO insert_probe (label) VALUES (?)",
                ("probe",),
            )
            self.assertEqual(generated_id, 1)
            self.assertEqual(
                connection.execute(
                    "SELECT label FROM insert_probe WHERE id=?", (generated_id,)
                ).fetchone()[0],
                "probe",
            )
            connection.rollback()
            self.assertEqual(
                connection.execute("SELECT COUNT(*) FROM insert_probe").fetchone()[0],
                0,
            )
        finally:
            connection.close()

    def test_rejects_non_insert_and_unsafe_id_column(self):
        connection = sqlite3.connect(":memory:")
        try:
            with self.assertRaises(ValueError):
                insert_one_returning_id(connection, "SELECT 1")
            with self.assertRaises(ValueError):
                insert_one_returning_id(
                    connection,
                    "INSERT INTO x (value) VALUES (?)",
                    ("x",),
                    id_column='id"; DROP TABLE x; --',
                )
        finally:
            connection.close()


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PostgreSQLGeneratedIdTests(unittest.TestCase):
    def test_returns_generated_identity_without_committing(self):
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN)
        try:
            connection.execute(
                "CREATE TEMP TABLE insert_probe "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label TEXT)"
            )
            generated_id = insert_one_returning_id(
                connection,
                "INSERT INTO insert_probe (label) VALUES (?)",
                ("probe",),
            )
            self.assertIsInstance(generated_id, int)
            self.assertEqual(
                connection.execute(
                    "SELECT label FROM insert_probe WHERE id=%s",
                    (generated_id,),
                ).fetchone()["label"],
                "probe",
            )
            connection.rollback()
        finally:
            connection.close()


if __name__ == "__main__":
    unittest.main()
