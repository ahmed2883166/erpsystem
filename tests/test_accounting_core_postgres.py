"""PostgreSQL integration coverage for the shared accounting posting core."""
from concurrent.futures import ThreadPoolExecutor
import os
import threading
import unittest
import uuid
from decimal import Decimal

from db_sql import executemany_compat

POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PostgreSQLAccountingCoreTests(unittest.TestCase):
    def test_post_journal_is_idempotent_and_reconciliation_uses_exact_numeric(self):
        from postgres_database import connect_postgres
        from accounting_core import post_journal, reconciliation_snapshot

        connection = connect_postgres(POSTGRES_DSN)
        schema = "nexus_accounting_core_" + uuid.uuid4().hex
        try:
            connection.execute(f'CREATE SCHEMA "{schema}"')
            connection.execute(f'SET LOCAL search_path TO "{schema}"')
            connection.execute("""
                CREATE TABLE accounts(
                    id BIGINT PRIMARY KEY,
                    code TEXT NOT NULL,
                    name_ar TEXT NOT NULL,
                    account_type TEXT NOT NULL,
                    parent_id BIGINT,
                    is_group BIGINT NOT NULL DEFAULT 0,
                    active BIGINT NOT NULL DEFAULT 1
                )
            """)
            connection.execute("""
                CREATE TABLE journal_entries(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    entry_date TEXT NOT NULL,
                    reference TEXT,
                    description TEXT NOT NULL,
                    status TEXT NOT NULL,
                    created_by BIGINT,
                    created_at TEXT NOT NULL
                )
            """)
            connection.execute("""
                CREATE TABLE journal_lines(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    entry_id BIGINT NOT NULL,
                    account_id BIGINT NOT NULL,
                    debit TEXT NOT NULL,
                    credit TEXT NOT NULL,
                    memo TEXT
                )
            """)
            executemany_compat(
                connection,
                "INSERT INTO accounts(id,code,name_ar,account_type,is_group,active) "
                "VALUES(?,?,?,?,?,?)",
                [
                    (1, "1110", "الصندوق", "asset", 0, 1),
                    (2, "4100", "الإيرادات", "revenue", 0, 1),
                ],
            )
            lines = [
                (1, "125.50", "0", "مدين الصندوق"),
                (2, "0", "125.50", "دائن الإيراد"),
            ]
            first_id = post_journal(
                connection, "2026-11-16", "PG-ACCOUNTING-001",
                "اختبار ترحيل القيد على PostgreSQL", lines, created_by=7,
            )
            second_id = post_journal(
                connection, "2026-11-16", "PG-ACCOUNTING-001",
                "اختبار ترحيل القيد على PostgreSQL", lines, created_by=7,
            )
            self.assertEqual(first_id, second_id)

            snapshot = reconciliation_snapshot(connection)
            self.assertEqual(snapshot["journal_totals"]["debit"], Decimal("125.50"))
            self.assertEqual(snapshot["journal_totals"]["credit"], Decimal("125.50"))
            self.assertEqual(snapshot["unbalanced"], [])
            self.assertEqual(
                connection.execute("SELECT COUNT(*) AS row_count FROM journal_entries").fetchone()["row_count"],
                1,
            )
            self.assertEqual(
                connection.execute("SELECT COUNT(*) AS row_count FROM journal_lines").fetchone()["row_count"],
                2,
            )
        finally:
            connection.rollback()
            connection.close()


    def test_concurrent_same_reference_posts_only_one_journal(self):
        from postgres_database import connect_postgres
        from accounting_core import post_journal

        schema = "nexus_accounting_race_" + uuid.uuid4().hex[:16]
        setup = connect_postgres(POSTGRES_DSN, autocommit=True)
        try:
            setup.execute(f'CREATE SCHEMA "{schema}"')
            setup.execute(f'SET search_path TO "{schema}"')
            setup.execute("""
                CREATE TABLE accounts(
                    id BIGINT PRIMARY KEY, code TEXT NOT NULL, name_ar TEXT NOT NULL,
                    account_type TEXT NOT NULL, parent_id BIGINT,
                    is_group BIGINT NOT NULL DEFAULT 0, active BIGINT NOT NULL DEFAULT 1
                )
            """)
            setup.execute("""
                CREATE TABLE journal_entries(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    entry_date TEXT NOT NULL, reference TEXT, description TEXT NOT NULL,
                    status TEXT NOT NULL, created_by BIGINT, created_at TEXT NOT NULL
                )
            """)
            setup.execute("""
                CREATE TABLE journal_lines(
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    entry_id BIGINT NOT NULL, account_id BIGINT NOT NULL,
                    debit TEXT NOT NULL, credit TEXT NOT NULL, memo TEXT
                )
            """)
            setup.execute(
                "INSERT INTO accounts(id,code,name_ar,account_type) VALUES"
                "(1,'1110','الصندوق','asset'),(2,'4100','الإيرادات','revenue')"
            )
        finally:
            setup.close()

        clients = 30
        start = threading.Barrier(clients)
        lines = [
            (1, "125.50", "0", "مدين الصندوق"),
            (2, "0", "125.50", "دائن الإيراد"),
        ]

        def post_from_client(client_number):
            connection = connect_postgres(POSTGRES_DSN)
            try:
                connection.execute(f'SET search_path TO "{schema}"')
                start.wait(timeout=20)
                entry_id = post_journal(
                    connection, "2026-11-18", "PG-CONCURRENT-SAME-REF",
                    "اختبار منع تكرار القيد المتزامن", lines,
                    created_by=client_number,
                )
                connection.commit()
                return entry_id
            except Exception:
                connection.rollback()
                raise
            finally:
                connection.close()

        cleanup = connect_postgres(POSTGRES_DSN, autocommit=True)
        try:
            with ThreadPoolExecutor(max_workers=clients) as pool:
                entry_ids = list(pool.map(post_from_client, range(1, clients + 1)))
            self.assertEqual(len(set(entry_ids)), 1)
            cleanup.execute(f'SET search_path TO "{schema}"')
            self.assertEqual(
                cleanup.execute("SELECT COUNT(*) FROM journal_entries").fetchone()[0],
                1,
            )
            self.assertEqual(
                cleanup.execute("SELECT COUNT(*) FROM journal_lines").fetchone()[0],
                2,
            )
        finally:
            cleanup.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            cleanup.close()


if __name__ == "__main__":
    unittest.main()
