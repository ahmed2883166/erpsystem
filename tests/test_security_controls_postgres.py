"""PostgreSQL coverage for database-agnostic journal reversal protection."""
import os
import unittest
import uuid

POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PostgreSQLSecurityControlTests(unittest.TestCase):
    def test_operational_links_are_detected_in_current_schema(self):
        from postgres_database import connect_postgres
        from security_controls import linked_operational_source

        schema = "nexus_security_links_" + uuid.uuid4().hex[:16]
        setup = connect_postgres(POSTGRES_DSN, autocommit=True)
        try:
            setup.execute(f'CREATE SCHEMA "{schema}"')
        finally:
            setup.close()

        connection = connect_postgres(POSTGRES_DSN)
        try:
            connection.execute(f'SET search_path TO "{schema}"')
            connection.execute("""
                CREATE TABLE journal_entries (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                )
            """)
            connection.execute("""
                CREATE TABLE supplier_bills (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    journal_entry_id BIGINT
                )
            """)
            connection.execute("""
                CREATE TABLE supplier_payments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    reversal_journal_entry_id BIGINT
                )
            """)
            connection.execute("INSERT INTO supplier_bills(journal_entry_id) VALUES (77)")
            connection.execute(
                "INSERT INTO supplier_payments(reversal_journal_entry_id) VALUES (88)"
            )

            self.assertEqual(linked_operational_source(connection, 77), "supplier_bills")
            self.assertEqual(linked_operational_source(connection, 88), "supplier_payments")
            self.assertIsNone(linked_operational_source(connection, 99))
        finally:
            connection.rollback()
            connection.close()
            cleanup = connect_postgres(POSTGRES_DSN, autocommit=True)
            try:
                cleanup.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            finally:
                cleanup.close()


if __name__ == "__main__":
    unittest.main()
