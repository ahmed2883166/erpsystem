"""Tests for the opt-in SQL placeholder adapter."""
import os
import sqlite3
import unittest

from db_sql import execute_compat, executemany_compat, qmark_to_format
from db_compat import execute_script


class QmarkTranslationTests(unittest.TestCase):
    def test_translates_only_unquoted_bind_markers(self):
        sql = (
            "SELECT ?, 'literal ? and '' quote', \"identifier?\", "
            "col FROM t WHERE a=? -- comment ?\n"
            "AND b=? /* block ? /* nested ? */ still ? */"
        )
        expected = (
            "SELECT %s, 'literal ? and '' quote', \"identifier?\", "
            "col FROM t WHERE a=%s -- comment ?\n"
            "AND b=%s /* block ? /* nested ? */ still ? */"
        )
        self.assertEqual(qmark_to_format(sql), expected)

    def test_preserves_postgresql_dollar_quoted_bodies(self):
        sql = "SELECT $tag$ ? ' text $tag$, ?"
        self.assertEqual(
            qmark_to_format(sql),
            "SELECT $tag$ ? ' text $tag$, %s",
        )

    def test_rejects_non_string_sql(self):
        with self.assertRaises(TypeError):
            qmark_to_format(None)

    def test_preserves_escaped_postgresql_json_question_mark_operators(self):
        sql = "SELECT payload ?? 'customer', payload ??| array['a'], id=? FROM events"
        expected = "SELECT payload ?? 'customer', payload ??| array['a'], id=%s FROM events"
        self.assertEqual(qmark_to_format(sql), expected)

    def test_sqlite_execution_keeps_qmark_parameters(self):
        connection = sqlite3.connect(":memory:")
        try:
            row = execute_compat(
                connection,
                "SELECT ? AS first_value, '?' AS literal_value",
                (37,),
            ).fetchone()
            self.assertEqual(row, (37, "?"))
        finally:
            connection.close()

    def test_sqlite_executemany_compat_preserves_qmark_parameters(self):
        connection = sqlite3.connect(":memory:")
        try:
            connection.execute("CREATE TABLE batch_probe(value INTEGER)")
            executemany_compat(
                connection, "INSERT INTO batch_probe(value) VALUES(?)",
                [(1,), (2,), (3,)],
            )
            self.assertEqual(
                connection.execute("SELECT value FROM batch_probe ORDER BY value").fetchall(),
                [(1,), (2,), (3,)],
            )
        finally:
            connection.close()


    def test_postgres_create_table_id_primary_key_becomes_identity(self):
        from db_sql import adapt_sql_for_postgresql

        sql = """CREATE TABLE IF NOT EXISTS sales_invoices (
            id INTEGER PRIMARY KEY, invoice_no TEXT NOT NULL,
            customer_id INTEGER REFERENCES customers(id)
        )"""
        adapted = adapt_sql_for_postgresql(sql)
        self.assertIn("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", adapted)
        self.assertIn("customer_id INTEGER REFERENCES customers(id)", adapted)

    def test_postgres_adapter_removes_sqlite_autoincrement_keyword(self):
        from db_sql import adapt_sql_for_postgresql

        adapted = adapt_sql_for_postgresql(
            "CREATE TABLE sample (id INTEGER PRIMARY KEY AUTOINCREMENT, label TEXT)"
        )
        self.assertIn("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", adapted)
        self.assertNotIn("AUTOINCREMENT", adapted)

    def test_postgres_adapter_does_not_rewrite_non_ddl_or_other_primary_keys(self):
        from db_sql import adapt_sql_for_postgresql

        self.assertEqual(
            adapt_sql_for_postgresql("SELECT id INTEGER PRIMARY KEY FROM sample"),
            "SELECT id INTEGER PRIMARY KEY FROM sample",
        )
        self.assertEqual(
            adapt_sql_for_postgresql("CREATE TABLE sample (code TEXT PRIMARY KEY)"),
            "CREATE TABLE sample (code TEXT PRIMARY KEY)",
        )


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PostgreSQLQmarkExecutionTests(unittest.TestCase):
    def test_postgresql_identity_ddl_generates_inserted_ids(self):
        import uuid
        from db_compat import insert_and_get_id
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN)
        schema = "nexus_identity_probe_" + uuid.uuid4().hex
        try:
            connection.execute(f'CREATE SCHEMA "{schema}"')
            connection.execute(f'SET LOCAL search_path TO "{schema}"')
            execute_compat(
                connection,
                "CREATE TABLE identity_probe (id INTEGER PRIMARY KEY, label TEXT NOT NULL)",
            )
            row_id = insert_and_get_id(
                connection,
                "INSERT INTO identity_probe(label) VALUES(?)",
                ("identity works",),
            )
            self.assertGreater(row_id, 0)
            row = connection.execute(
                "SELECT id, label FROM identity_probe WHERE id=%s", (row_id,)
            ).fetchone()
            self.assertEqual(row["id"], row_id)
            self.assertEqual(row["label"], "identity works")
        finally:
            connection.rollback()
            connection.close()

    def test_execute_script_runs_multiple_postgresql_statements_safely(self):
        import uuid
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN)
        schema = "nexus_script_probe_" + uuid.uuid4().hex
        try:
            connection.execute(f'CREATE SCHEMA "{schema}"')
            connection.execute(f'SET LOCAL search_path TO "{schema}"')
            execute_script(connection, """
                CREATE TABLE script_probe (
                    id INTEGER PRIMARY KEY,
                    label TEXT NOT NULL
                );
                INSERT INTO script_probe(label) VALUES('semicolon; stays inside text');
                CREATE TABLE script_probe_audit (
                    note TEXT NOT NULL
                );
                INSERT INTO script_probe_audit(note)
                    VALUES('second statement group');
            """)
            row = connection.execute(
                "SELECT id,label FROM script_probe"
            ).fetchone()
            self.assertEqual(row["id"], 1)
            self.assertEqual(row["label"], "semicolon; stays inside text")
            audit = connection.execute(
                "SELECT note FROM script_probe_audit"
            ).fetchone()
            self.assertEqual(audit["note"], "second statement group")
        finally:
            # The schema and all test objects are rolled back, not persisted.
            connection.rollback()
            connection.close()

    def test_qmark_parameters_execute_on_postgresql(self):
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN)
        try:
            row = execute_compat(
                connection,
                "SELECT ?::integer AS value, ?::numeric AS exact_amount",
                (42, "1234567890.123456"),
            ).fetchone()
            self.assertEqual(row["value"], 42)
            self.assertEqual(str(row["exact_amount"]), "1234567890.123456")
            connection.execute("CREATE TEMP TABLE batch_probe(value INTEGER)")
            executemany_compat(
                connection, "INSERT INTO batch_probe(value) VALUES(?)",
                [(4,), (5,), (6,)],
            )
            values = connection.execute(
                "SELECT value FROM batch_probe ORDER BY value"
            ).fetchall()
            self.assertEqual([item["value"] for item in values], [4, 5, 6])
        finally:
            connection.rollback()
            connection.close()


if __name__ == "__main__":
    unittest.main()
