"""PostgreSQL integration coverage for additive tax schema initialization."""
import os
import unittest
import uuid

import tax_center


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class TaxPostgreSQLSchemaInitializationTests(unittest.TestCase):
    def test_tax_schema_initialization_is_additive_and_idempotent(self):
        from postgres_database import connect_postgres

        schema = "nexus_tax_schema_" + uuid.uuid4().hex
        admin = connect_postgres(
            POSTGRES_DSN, application_name="NEXUS tax schema integration test"
        )
        original_db = tax_center._db

        def open_schema_connection():
            connection = connect_postgres(
                POSTGRES_DSN, application_name="NEXUS tax schema integration test"
            )
            connection.execute(f'SET search_path TO "{schema}"')
            return connection

        try:
            admin.execute(f'CREATE SCHEMA "{schema}"')
            admin.commit()
            setup = open_schema_connection()
            try:
                setup.execute("""
                    CREATE TABLE sales_invoices (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        invoice_no TEXT NOT NULL,
                        total_amount TEXT NOT NULL
                    )
                """)
                setup.execute("""
                    CREATE TABLE supplier_bills (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        bill_no TEXT NOT NULL,
                        total_amount TEXT NOT NULL
                    )
                """)
                setup.execute(
                    "INSERT INTO sales_invoices(invoice_no,total_amount) VALUES(%s,%s)",
                    ("SI-OLD-1", "1250.75"),
                )
                setup.execute(
                    "INSERT INTO supplier_bills(bill_no,total_amount) VALUES(%s,%s)",
                    ("PB-OLD-1", "875.25"),
                )
                setup.commit()
            finally:
                setup.close()

            tax_center._db = open_schema_connection
            tax_center.initialize_tax_schema()

            check = open_schema_connection()
            try:
                sales = check.execute("""
                    SELECT invoice_no,total_amount,tax_treatment,tax_reference,tax_notes
                    FROM sales_invoices WHERE invoice_no=%s
                """, ("SI-OLD-1",)).fetchone()
                self.assertEqual(sales["total_amount"], "1250.75")
                self.assertEqual(sales["tax_treatment"], "standard")
                self.assertEqual(sales["tax_reference"], "")
                supplier = check.execute("""
                    SELECT bill_no,total_amount,tax_treatment,input_vat_deductible_percent
                    FROM supplier_bills WHERE bill_no=%s
                """, ("PB-OLD-1",)).fetchone()
                self.assertEqual(supplier["total_amount"], "875.25")
                self.assertEqual(supplier["tax_treatment"], "standard")
                self.assertEqual(supplier["input_vat_deductible_percent"], "100")
                self.assertTrue(check.execute("""
                    SELECT EXISTS(
                        SELECT 1 FROM information_schema.tables
                        WHERE table_schema=%s
                          AND table_name='tax_document_reference_audit'
                    ) AS present
                """, (schema,)).fetchone()["present"])
            finally:
                check.close()

            tax_center.initialize_tax_schema()
            verify = open_schema_connection()
            try:
                self.assertEqual(
                    verify.execute("SELECT COUNT(*) AS count FROM sales_invoices").fetchone()["count"],
                    1,
                )
                self.assertEqual(
                    verify.execute("SELECT COUNT(*) AS count FROM supplier_bills").fetchone()["count"],
                    1,
                )
                self.assertEqual(
                    verify.execute("SELECT COUNT(*) AS count FROM tax_document_reference_audit").fetchone()["count"],
                    0,
                )
            finally:
                verify.close()
        finally:
            tax_center._db = original_db
            admin.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            admin.commit()
            admin.close()


if __name__ == "__main__":
    unittest.main()
