"""PostgreSQL acceptance tests for payroll and Friday allowance journal shapes.

Uses a disposable schema and real PostgreSQL NUMERIC arithmetic through the
shared accounting posting core. No application data directory is accessed.
"""
import os
import unittest
import uuid
from decimal import Decimal

from postgres_database import connect_postgres
from accounting_core import post_journal, reconciliation_snapshot
from db_sql import executemany_compat
import workforce


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PostgreSQLWorkforcePostingTests(unittest.TestCase):
    def setUp(self):
        self.schema = "nexus_workforce_post_" + uuid.uuid4().hex[:12]
        self.conn = connect_postgres(POSTGRES_DSN)
        self.conn.execute(f'CREATE SCHEMA "{self.schema}"')
        self.conn.execute(f'SET search_path TO "{self.schema}"')
        self.conn.execute("""
            CREATE TABLE accounts(
                id BIGINT PRIMARY KEY, code TEXT NOT NULL, name_ar TEXT NOT NULL,
                account_type TEXT NOT NULL, is_group BIGINT NOT NULL DEFAULT 0,
                active BIGINT NOT NULL DEFAULT 1
            )
        """)
        self.conn.execute("""
            CREATE TABLE journal_entries(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entry_date TEXT NOT NULL, reference TEXT, description TEXT NOT NULL,
                status TEXT NOT NULL, created_by BIGINT, created_at TEXT NOT NULL
            )
        """)
        self.conn.execute("""
            CREATE TABLE journal_lines(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entry_id BIGINT NOT NULL, account_id BIGINT NOT NULL,
                debit TEXT NOT NULL, credit TEXT NOT NULL, memo TEXT,
                branch_id BIGINT, cost_center_id BIGINT, project_id BIGINT
            )
        """)
        executemany_compat(self.conn,
            "INSERT INTO accounts(id,code,name_ar,account_type,is_group,active) VALUES(?,?,?,?,?,?)",
            [
                (1, "6100", "مصروف الأجور", "expense", 0, 1),
                (2, "6110", "مصروف حصة الشركة بالتأمينات", "expense", 0, 1),
                (3, "2110", "مرتبات مستحقة", "liability", 0, 1),
                (4, "2120", "ضريبة وتأمينات مستحقة", "liability", 0, 1),
                (5, "2130", "خصومات أخرى مستحقة", "liability", 0, 1),
                (6, "1300", "سلف الموظفين", "asset", 0, 1),
                (7, "6200", "مصروف بدل الجمعة", "expense", 0, 1),
                (8, "2140", "بدل الجمعة المستحق", "liability", 0, 1),
            ])
        self.conn.commit()

    def tearDown(self):
        try:
            self.conn.rollback()
            self.conn.autocommit = True
            self.conn.execute(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')
        finally:
            self.conn.close()

    def test_monthly_payroll_journal_balances_and_is_idempotent(self):
        # Mirrors the posting composition in workforce.post_payroll:
        # gross wages + employer insurance expense are offset by net pay,
        # advances, other deductions, penalties, tax/stamp and total insurance.
        payroll_lines = [
            (1, "11000.00", "0", "إجمالي الأجور"),
            (2, "1500.00", "0", "حصة الشركة بالتأمينات"),
            (3, "0", "9000.00", "صافي مستحقات الموظفين"),
            (6, "0", "100.00", "استرداد سلف العاملين"),
            (5, "0", "200.00", "خصومات أخرى"),
            (5, "0", "100.00", "جزاءات الموظفين"),
            (4, "0", "500.00", "ضريبة المرتبات"),
            (4, "0", "100.00", "دمغة المرتبات"),
            (4, "0", "2500.00", "تأمينات الموظف وصاحب العمل"),
        ]
        first = post_journal(
            self.conn, "2026-11-01", "PAYROLL-2026-11-RUN-71",
            "مرتبات شهر 2026-11", payroll_lines, created_by=9,
        )
        second = post_journal(
            self.conn, "2026-11-01", "PAYROLL-2026-11-RUN-71",
            "مرتبات شهر 2026-11", payroll_lines, created_by=9,
        )
        self.assertEqual(first, second)
        snapshot = reconciliation_snapshot(self.conn)
        self.assertEqual(snapshot["journal_totals"]["debit"], Decimal("12500.00"))
        self.assertEqual(snapshot["journal_totals"]["credit"], Decimal("12500.00"))
        self.assertEqual(snapshot["unbalanced"], [])
        self.assertEqual(self.conn.execute("SELECT COUNT(*) FROM journal_entries").fetchone()[0], 1)
        self.assertEqual(self.conn.execute("SELECT COUNT(*) FROM journal_lines").fetchone()[0], 9)

        with self.assertRaisesRegex(ValueError, "رقم مرجع القيد مستخدم"):
            post_journal(
                self.conn, "2026-11-01", "PAYROLL-2026-11-RUN-71",
                "مرتبات شهر مختلف", payroll_lines, created_by=9,
            )

    def test_friday_allowance_journal_preserves_analytic_dimensions(self):
        dimensions = {"branch_id": 3, "cost_center_id": 12, "project_id": 25}
        lines = [
            (7, "400.00", "0", "بدل جمعة - موظف 1", dimensions),
            (7, "200.00", "0", "بدل جمعة - موظف 2", dimensions),
            (8, "0", "600.00", "إجمالي بدل الجمعة المستحق"),
        ]
        entry_id = post_journal(
            self.conn, "2026-11-30", "FRIDAY-ALLOWANCE-2026-11",
            "استحقاق بدل العمل أيام الجمعة عن 2026-11", lines, created_by=9,
        )
        rows = self.conn.execute(
            "SELECT account_id,debit,credit,branch_id,cost_center_id,project_id "
            "FROM journal_lines WHERE entry_id=%s ORDER BY id",
            (entry_id,),
        ).fetchall()
        self.assertEqual(len(rows), 3)
        self.assertEqual(
            [(row["branch_id"], row["cost_center_id"], row["project_id"]) for row in rows[:2]],
            [(3, 12, 25), (3, 12, 25)],
        )
        self.assertEqual(rows[2]["credit"], "600.00")
        snapshot = reconciliation_snapshot(self.conn)
        self.assertEqual(snapshot["journal_totals"]["debit"], Decimal("600.00"))
        self.assertEqual(snapshot["journal_totals"]["credit"], Decimal("600.00"))
        self.assertEqual(snapshot["unbalanced"], [])

    def test_friday_attendance_predicate_and_grouping_are_postgresql_native(self):
        self.conn.execute("""
            CREATE TABLE attendance_records(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                employee_code TEXT NOT NULL, attendance_date TEXT NOT NULL
            )
        """)
        self.conn.execute("""
            INSERT INTO attendance_records(employee_code,attendance_date)
            VALUES ('E001','2026-11-20'), ('E002','2026-11-20'), ('E003','2026-11-21')
        """)
        predicate = workforce._friday_attendance_predicate(self.conn)
        grouped = workforce._group_concat_expression(self.conn, "a.employee_code")
        rows = self.conn.execute(
            f"SELECT {grouped} AS employees FROM attendance_records a WHERE {predicate}"
        ).fetchone()
        self.assertEqual(rows["employees"], "E001, E002")


if __name__ == "__main__":
    unittest.main()
