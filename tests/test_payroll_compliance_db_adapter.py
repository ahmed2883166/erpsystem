"""Database-driver integration tests for payroll compliance SQL helpers."""
import os
import sqlite3
import unittest

from payroll_compliance import _execute, _executemany


class PayrollComplianceSQLiteAdapterTests(unittest.TestCase):
    def test_qmark_execution_helpers_work_on_sqlite(self):
        connection = sqlite3.connect(":memory:")
        try:
            _execute(
                connection,
                "CREATE TABLE payroll_adapter_probe (id INTEGER PRIMARY KEY, amount NUMERIC)",
            )
            _execute(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                ("12.50",),
            )
            _executemany(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                [("1.25",), ("2.25",)],
            )
            row = _execute(
                connection,
                "SELECT COUNT(*) AS row_count FROM payroll_adapter_probe",
            ).fetchone()
            self.assertEqual(row[0], 3)
        finally:
            connection.close()


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PayrollCompliancePostgreSQLAdapterTests(unittest.TestCase):
    def test_qmark_execution_helpers_work_on_postgresql(self):
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN, application_name="NEXUS payroll adapter test")
        try:
            _execute(
                connection,
                "CREATE TEMP TABLE payroll_adapter_probe "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount NUMERIC(12,2))",
            )
            _execute(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                ("12.50",),
            )
            _executemany(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                [("1.25",), ("2.25",)],
            )
            row = _execute(
                connection,
                "SELECT COUNT(*) AS row_count FROM payroll_adapter_probe",
            ).fetchone()
            self.assertEqual(row["row_count"], 3)
        finally:
            connection.rollback()
            connection.close()


if __name__ == "__main__":
    unittest.main()
