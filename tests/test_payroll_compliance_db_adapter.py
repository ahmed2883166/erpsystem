"""Database-driver integration tests for payroll compliance SQL helpers."""
import os
import sqlite3
import unittest

from payroll_compliance import _execute, _executemany


class PayrollComplianceSQLiteAdapterTests(unittest.TestCase):
    def test_qmark_execution_helpers_work_on_sqlite(self):
        connection = sqlite3.connect(":memory:")
        try:
            _execute(
                connection,
                "CREATE TABLE payroll_adapter_probe (id INTEGER PRIMARY KEY, amount NUMERIC)",
            )
            _execute(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                ("12.50",),
            )
            _executemany(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                [("1.25",), ("2.25",)],
            )
            row = _execute(
                connection,
                "SELECT COUNT(*) AS row_count FROM payroll_adapter_probe",
            ).fetchone()
            self.assertEqual(row[0], 3)
        finally:
            connection.close()


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PayrollCompliancePostgreSQLAdapterTests(unittest.TestCase):
    def test_qmark_execution_helpers_work_on_postgresql(self):
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN, application_name="NEXUS payroll adapter test")
        try:
            _execute(
                connection,
                "CREATE TEMP TABLE payroll_adapter_probe "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, amount NUMERIC(12,2))",
            )
            _execute(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                ("12.50",),
            )
            _executemany(
                connection,
                "INSERT INTO payroll_adapter_probe(amount) VALUES (?)",
                [("1.25",), ("2.25",)],
            )
            row = _execute(
                connection,
                "SELECT COUNT(*) AS row_count FROM payroll_adapter_probe",
            ).fetchone()
            self.assertEqual(row["row_count"], 3)
        finally:
            connection.rollback()
            connection.close()



class PayrollCompliancePostgreSQLSchemaInitializationTests(unittest.TestCase):
    """Exercise the real payroll schema initializer inside an isolated PG schema."""

    @unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
    def test_schema_initialization_is_idempotent_and_preserves_reviewed_rules(self):
        import uuid

        import payroll_compliance
        from postgres_database import connect_postgres

        schema = "nexus_payroll_rules_" + uuid.uuid4().hex
        admin = connect_postgres(
            POSTGRES_DSN, application_name="NEXUS payroll schema initialization test"
        )
        original_db = payroll_compliance._db
        try:
            admin.execute(f'CREATE SCHEMA "{schema}"')
            admin.commit()

            def open_schema_connection():
                connection = connect_postgres(
                    POSTGRES_DSN, application_name="NEXUS payroll schema initialization test"
                )
                connection.execute(f'SET search_path TO "{schema}"')
                return connection

            setup = open_schema_connection()
            try:
                setup.execute("""
                    CREATE TABLE company_settings(
                        setting_key TEXT PRIMARY KEY,
                        setting_value TEXT NOT NULL
                    )
                """)
                setup.execute(
                    "INSERT INTO company_settings(setting_key,setting_value) VALUES('tax_country','EG')"
                )
                setup.execute("""
                    CREATE TABLE accounts(
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                """)
                setup.execute("""
                    CREATE TABLE employees(
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                """)
                setup.execute("""
                    CREATE TABLE payroll_lines(
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                """)
                setup.commit()
            finally:
                setup.close()

            payroll_compliance._db = open_schema_connection
            payroll_compliance.initialize_payroll_compliance_schema()

            check = open_schema_connection()
            try:
                first_rule = check.execute("""
                    SELECT id,employee_insurance_rate
                    FROM payroll_rule_sets
                    WHERE country_code='EG' AND category_code='local'
                      AND effective_from='2026-01-01'
                """).fetchone()
                self.assertIsNotNone(first_rule)
                first_tier_count = check.execute(
                    "SELECT COUNT(*) AS count FROM payroll_tax_tier_brackets WHERE rule_set_id=%s",
                    (first_rule["id"],),
                ).fetchone()["count"]
                self.assertGreater(first_tier_count, 0)
                self.assertIn("insurance_enabled", {
                    row["column_name"] for row in check.execute("""
                        SELECT column_name FROM information_schema.columns
                        WHERE table_schema=%s AND table_name='employees'
                    """, (schema,)).fetchall()
                })
                check.execute(
                    "UPDATE payroll_rule_sets SET employee_insurance_rate='12.25' WHERE id=%s",
                    (first_rule["id"],),
                )
                check.commit()
            finally:
                check.close()

            # A second initialization must neither duplicate the preset nor
            # overwrite a rate that an accountant has reviewed and changed.
            payroll_compliance.initialize_payroll_compliance_schema()
            verify = open_schema_connection()
            try:
                rules = verify.execute("""
                    SELECT id,employee_insurance_rate FROM payroll_rule_sets
                    WHERE country_code='EG' AND category_code='local'
                      AND effective_from='2026-01-01'
                """).fetchall()
                self.assertEqual(len(rules), 1)
                self.assertEqual(rules[0]["employee_insurance_rate"], "12.25")
                second_tier_count = verify.execute(
                    "SELECT COUNT(*) AS count FROM payroll_tax_tier_brackets WHERE rule_set_id=%s",
                    (rules[0]["id"],),
                ).fetchone()["count"]
                self.assertEqual(second_tier_count, first_tier_count)
                self.assertTrue(verify.execute("""
                    SELECT EXISTS(
                        SELECT 1 FROM information_schema.table_constraints
                        WHERE constraint_schema=%s
                          AND table_name='payroll_statutory_payments'
                          AND constraint_type='FOREIGN KEY'
                    ) AS has_foreign_keys
                """, (schema,)).fetchone()["has_foreign_keys"])
            finally:
                verify.close()
        finally:
            payroll_compliance._db = original_db
            admin.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            admin.commit()
            admin.close()


if __name__ == "__main__":
    unittest.main()
