import os
import sqlite3
import unittest

import workforce


class FakePostgresConnection:
    __module__ = "psycopg"


class WorkforceDialectSQLTests(unittest.TestCase):
    def test_group_concat_expression_is_dialect_specific(self):
        sqlite_connection = sqlite3.connect(":memory:")
        try:
            self.assertEqual(
                workforce._group_concat_expression(sqlite_connection, "employee_id"),
                "GROUP_CONCAT(employee_id, ', ')",
            )
        finally:
            sqlite_connection.close()

        self.assertEqual(
            workforce._group_concat_expression(FakePostgresConnection(), "employee_id"),
            "STRING_AGG(CAST(employee_id AS TEXT), ', ')",
        )

    def test_friday_predicate_is_dialect_specific(self):
        sqlite_connection = sqlite3.connect(":memory:")
        try:
            self.assertEqual(
                workforce._friday_attendance_predicate(sqlite_connection),
                "strftime('%w',a.attendance_date)='5'",
            )
        finally:
            sqlite_connection.close()

        self.assertEqual(
            workforce._friday_attendance_predicate(FakePostgresConnection()),
            "EXTRACT(DOW FROM CAST(a.attendance_date AS DATE))=5",
        )


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class WorkforcePostgreSQLDialectIntegrationTests(unittest.TestCase):
    """Execute workforce SQL fragments against a real PostgreSQL connection."""

    def test_friday_filter_and_employee_aggregation_execute_on_postgresql(self):
        from postgres_database import connect_postgres

        connection = connect_postgres(
            POSTGRES_DSN, application_name="NEXUS workforce dialect integration test"
        )
        try:
            connection.execute("""
                CREATE TEMP TABLE attendance_records (
                    employee_id BIGINT NOT NULL,
                    attendance_date TEXT NOT NULL
                )
            """)
            connection.executemany(
                "INSERT INTO attendance_records(employee_id,attendance_date) VALUES (%s,%s)",
                [
                    (10, "2026-11-20"),  # Friday
                    (11, "2026-11-19"),  # Thursday
                    (12, "2026-11-27"),  # Friday
                ],
            )
            expression = workforce._group_concat_expression(connection, "a.employee_id")
            friday = workforce._friday_attendance_predicate(connection)
            row = connection.execute(
                f"SELECT {expression} AS employee_ids FROM attendance_records a WHERE {friday}"
            ).fetchone()
            self.assertEqual(set(row["employee_ids"].split(", ")), {"10", "12"})
        finally:
            connection.rollback()
            connection.close()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class WorkforcePostgreSQLSchemaInitializationTests(unittest.TestCase):
    """Exercise the real workforce schema initializer in a disposable PG schema."""

    def test_schema_initialization_is_idempotent(self):
        import uuid

        from postgres_database import connect_postgres

        schema = "nexus_workforce_" + uuid.uuid4().hex
        admin = connect_postgres(
            POSTGRES_DSN, application_name="NEXUS workforce schema initialization test"
        )
        original_db = workforce._db
        try:
            admin.execute(f'CREATE SCHEMA "{schema}"')
            admin.commit()

            def open_schema_connection():
                connection = connect_postgres(
                    POSTGRES_DSN, application_name="NEXUS workforce schema initialization test"
                )
                connection.execute(f'SET search_path TO "{schema}"')
                return connection

            setup = open_schema_connection()
            try:
                setup.execute("""
                    CREATE TABLE accounts (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                """)
                setup.commit()
            finally:
                setup.close()

            workforce._db = open_schema_connection
            workforce.initialize_workforce_schema()

            check = open_schema_connection()
            try:
                tables = {
                    row["table_name"] for row in check.execute("""
                        SELECT table_name FROM information_schema.tables
                        WHERE table_schema=%s AND table_type='BASE TABLE'
                    """, (schema,)).fetchall()
                }
                self.assertTrue({
                    "employees", "payroll_runs", "payroll_lines",
                    "attendance_records", "employee_employment_history",
                    "friday_allowance_batches",
                }.issubset(tables))
                employee_columns = {
                    row["column_name"] for row in check.execute("""
                        SELECT column_name FROM information_schema.columns
                        WHERE table_schema=%s AND table_name='employees'
                    """, (schema,)).fetchall()
                }
                self.assertTrue({"insurance_enabled", "friday_work_eligible", "insured_wage"}.issubset(employee_columns))
                migration_count = check.execute(
                    "SELECT COUNT(*) AS count FROM workforce_migrations"
                ).fetchone()["count"]
                history_count = check.execute(
                    "SELECT COUNT(*) AS count FROM employee_employment_history"
                ).fetchone()["count"]
                self.assertEqual(history_count, 0)
                self.assertGreaterEqual(migration_count, 1)
                self.assertTrue(check.execute("""
                    SELECT EXISTS(
                        SELECT 1 FROM information_schema.table_constraints
                        WHERE constraint_schema=%s AND table_name='payroll_lines'
                          AND constraint_type='FOREIGN KEY'
                    ) AS has_foreign_key
                """, (schema,)).fetchone()["has_foreign_key"])
            finally:
                check.close()

            workforce.initialize_workforce_schema()
            verify = open_schema_connection()
            try:
                self.assertEqual(
                    verify.execute("SELECT COUNT(*) AS count FROM workforce_migrations").fetchone()["count"],
                    migration_count,
                )
                self.assertEqual(
                    verify.execute("SELECT COUNT(*) AS count FROM employee_employment_history").fetchone()["count"],
                    history_count,
                )
            finally:
                verify.close()
        finally:
            workforce._db = original_db
            admin.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            admin.commit()
            admin.close()


if __name__ == "__main__":
    unittest.main()
