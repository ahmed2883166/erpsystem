"""PostgreSQL integration coverage for isolated FX transaction helpers.

These tests use a unique disposable schema and roll it back/drop it; they never
connect to the application's SQLite data directory.
"""
import os
import unittest
import uuid

import currency_center


@unittest.skipUnless(
    os.environ.get("NEXUS_TEST_POSTGRES_DSN"),
    "PostgreSQL integration DSN not configured",
)
class CurrencyPostgreSQLHelperTests(unittest.TestCase):
    def setUp(self):
        import psycopg
        from psycopg.rows import dict_row

        self.schema = "nexus_fx_helpers_" + uuid.uuid4().hex[:12]
        self.conn = psycopg.connect(
            os.environ["NEXUS_TEST_POSTGRES_DSN"], row_factory=dict_row
        )
        self.conn.execute(f'CREATE SCHEMA "{self.schema}"')
        self.conn.commit()
        self.conn.execute(f'SET search_path TO "{self.schema}"')
        self.conn.commit()
        self.conn.execute("""
            CREATE TABLE fx_transactions (
                id BIGINT PRIMARY KEY,
                reference TEXT NOT NULL,
                party_type TEXT NOT NULL,
                currency_code TEXT NOT NULL,
                transaction_date TEXT NOT NULL,
                balance_foreign TEXT NOT NULL,
                balance_base TEXT NOT NULL,
                status TEXT NOT NULL
            )
        """)
        self.conn.execute("""
            CREATE TABLE fx_settlements (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                transaction_id BIGINT NOT NULL,
                settlement_date TEXT NOT NULL
            )
        """)
        self.conn.execute("""
            CREATE TABLE fx_revaluations (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                transaction_id BIGINT NOT NULL,
                revaluation_date TEXT NOT NULL
            )
        """)
        self.conn.execute("""
            INSERT INTO fx_transactions
                (id, reference, party_type, currency_code, transaction_date,
                 balance_foreign, balance_base, status)
            VALUES (1, 'FX-TEST-1', 'receivable', 'USD', '2026-01-01',
                    '100.00', '5000.00', 'open')
        """)
        self.conn.execute("""
            INSERT INTO fx_settlements(transaction_id, settlement_date)
            VALUES (1, '2026-02-01'), (1, '2026-03-01')
        """)
        self.conn.execute("""
            INSERT INTO fx_revaluations(transaction_id, revaluation_date)
            VALUES (1, '2026-03-15')
        """)
        self.conn.commit()

    def tearDown(self):
        try:
            self.conn.rollback()
            self.conn.autocommit = True
            self.conn.execute(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')
        finally:
            self.conn.close()

    def test_lock_latest_dates_compare_and_set_and_transaction_state(self):
        from db_compat import transaction_is_active

        self.assertFalse(transaction_is_active(self.conn))
        self.assertTrue(currency_center._begin_fx_write(self.conn))
        self.assertTrue(transaction_is_active(self.conn))

        row = currency_center._open_fx_transaction_for_update(self.conn, 1)
        self.assertEqual(row["reference"], "FX-TEST-1")
        self.assertEqual(row["balance_foreign"], "100.00")
        self.assertEqual(
            currency_center._latest_fx_date(self.conn, "settlement", 1),
            "2026-03-01",
        )
        self.assertEqual(
            currency_center._latest_fx_date(self.conn, "revaluation", 1),
            "2026-03-15",
        )

        currency_center.update_open_fx_balance(
            self.conn, 1, "100.00", "40.00", "2000.00"
        )
        updated = self.conn.execute(
            "SELECT balance_foreign, balance_base, status "
            "FROM fx_transactions WHERE id=1"
        ).fetchone()
        self.assertEqual(updated["balance_foreign"], "40.00")
        self.assertEqual(updated["balance_base"], "2000.00")
        self.assertEqual(updated["status"], "open")

        with self.assertRaisesRegex(ValueError, "تغير رصيد المعاملة"):
            currency_center.update_open_fx_balance(
                self.conn, 1, "100.00", "0", "0"
            )

        self.conn.rollback()
        self.assertFalse(transaction_is_active(self.conn))
        unchanged = self.conn.execute(
            "SELECT balance_foreign, balance_base FROM fx_transactions WHERE id=1"
        ).fetchone()
        self.assertEqual(unchanged["balance_foreign"], "100.00")
        self.assertEqual(unchanged["balance_base"], "5000.00")


if __name__ == "__main__":
    unittest.main()
