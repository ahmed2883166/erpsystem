"""Database-neutral account chart metadata inspection tests."""
import os
import sqlite3
import unittest

from chart_templates import (
    _account_columns,
    seed_activity_chart,
    ensure_activity_chart_accounts,
    migrate_vat_accounts,
)


class AccountChartMetadataSQLiteTests(unittest.TestCase):
    def test_account_columns_are_read_from_sqlite(self):
        conn = sqlite3.connect(":memory:")
        conn.row_factory = sqlite3.Row
        try:
            conn.execute("CREATE TABLE accounts (id INTEGER PRIMARY KEY, code TEXT, name_ar TEXT)")
            self.assertEqual(_account_columns(conn), {"id", "code", "name_ar"})
        finally:
            conn.close()


@unittest.skipUnless(os.environ.get("NEXUS_TEST_POSTGRES_DSN"), "PostgreSQL integration DSN not configured")
class AccountChartMetadataPostgreSQLTests(unittest.TestCase):
    def test_account_columns_in_rolled_back_schema(self):
        import uuid
        import psycopg
        from psycopg.rows import dict_row

        schema = "nexus_chart_meta_" + uuid.uuid4().hex[:12]
        conn = psycopg.connect(os.environ["NEXUS_TEST_POSTGRES_DSN"], row_factory=dict_row)
        try:
            try:
                with conn.transaction():
                    conn.execute(f'CREATE SCHEMA "{schema}"')
                    conn.execute(f'SET LOCAL search_path TO "{schema}"')
                    conn.execute("""
                        CREATE TABLE accounts (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            code TEXT UNIQUE NOT NULL,
                            name_ar TEXT NOT NULL,
                            account_type TEXT NOT NULL,
                            parent_id BIGINT REFERENCES accounts(id),
                            is_group INTEGER NOT NULL DEFAULT 0,
                            active INTEGER NOT NULL DEFAULT 1
                        )
                    """)
                    self.assertEqual(
                        _account_columns(conn),
                        {"id", "code", "name_ar", "account_type", "parent_id",
                         "is_group", "active"},
                    )
                    seeded = seed_activity_chart(conn, "commercial")
                    self.assertTrue(seeded)
                    self.assertEqual(
                        conn.execute("SELECT COUNT(*) AS n FROM accounts").fetchone()["n"],
                        len(seeded),
                    )

                    conn.execute("DROP TABLE accounts")
                    conn.execute("""
                        CREATE TABLE accounts (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            code TEXT UNIQUE NOT NULL,
                            name_ar TEXT NOT NULL,
                            account_type TEXT NOT NULL,
                            parent_id BIGINT REFERENCES accounts(id),
                            is_group INTEGER NOT NULL DEFAULT 0,
                            active INTEGER NOT NULL DEFAULT 1
                        )
                    """)
                    conn.execute("""
                        INSERT INTO accounts(id,code,name_ar,account_type,parent_id,is_group)
                        VALUES (42,'1000','الأصول','asset',NULL,1)
                    """)
                    # Explicit IDs in a fixture do not advance an identity sequence.
                    conn.execute("""
                        SELECT setval(
                            pg_get_serial_sequence('accounts', 'id'),
                            (SELECT MAX(id) FROM accounts)
                        )
                    """)
                    ensure_activity_chart_accounts(conn, "commercial")
                    first_ids = {
                        row["code"]: row["id"]
                        for row in conn.execute("SELECT code,id FROM accounts").fetchall()
                    }
                    ensure_activity_chart_accounts(conn, "commercial")
                    second_ids = {
                        row["code"]: row["id"]
                        for row in conn.execute("SELECT code,id FROM accounts").fetchall()
                    }
                    self.assertEqual(first_ids, second_ids)
                    self.assertEqual(first_ids["1000"], 42)
                    self.assertIn("2190", first_ids)
                    self.assertIn("1165", first_ids)
                    self.assertEqual(
                        conn.execute(
                            "SELECT parent_id FROM accounts WHERE code='1100'"
                        ).fetchone()["parent_id"],
                        42,
                    )
                    raise RuntimeError("rollback disposable schema")
            except RuntimeError as exc:
                self.assertEqual(str(exc), "rollback disposable schema")
        finally:
            conn.close()


    def test_vat_migration_preserves_account_ids_and_journal_links(self):
        import uuid
        import psycopg
        from psycopg.rows import dict_row

        schema = "nexus_chart_vat_" + uuid.uuid4().hex[:12]
        conn = psycopg.connect(os.environ["NEXUS_TEST_POSTGRES_DSN"], row_factory=dict_row)
        try:
            try:
                with conn.transaction():
                    conn.execute(f'CREATE SCHEMA "{schema}"')
                    conn.execute(f'SET LOCAL search_path TO "{schema}"')
                    conn.execute("""
                        CREATE TABLE accounts (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            code TEXT UNIQUE NOT NULL,
                            name_ar TEXT NOT NULL,
                            account_type TEXT NOT NULL,
                            parent_id BIGINT REFERENCES accounts(id),
                            is_group INTEGER NOT NULL DEFAULT 0,
                            active INTEGER NOT NULL DEFAULT 1
                        )
                    """)
                    conn.execute("""
                        CREATE TABLE journal_lines (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            account_id BIGINT NOT NULL REFERENCES accounts(id)
                        )
                    """)
                    with conn.cursor() as cur:
                        cur.executemany("""
                            INSERT INTO accounts(id,code,name_ar,account_type,parent_id,is_group)
                            VALUES(%s,%s,%s,%s,%s,%s)
                        """, [
                            (11, "1100", "الأصول المتداولة", "asset", None, 1),
                            (20, "2000", "الالتزامات", "liability", None, 1),
                            (12, "2120", "ضريبة القيمة المضافة - مخرجات", "liability", 20, 0),
                            (13, "2130", "حساب التزامات قديم", "liability", 20, 0),
                        ])
                        cur.executemany(
                            "INSERT INTO journal_lines(account_id) VALUES(%s)",
                            [(12,), (13,)],
                        )
                    migrate_vat_accounts(conn, "medical")
                    by_code = {
                        row["code"]: row["id"]
                        for row in conn.execute("SELECT code,id FROM accounts").fetchall()
                    }
                    self.assertEqual(by_code["2130"], 12)
                    self.assertEqual(by_code["2140"], 13)
                    self.assertIn("1165", by_code)
                    linked_ids = {
                        row["account_id"]
                        for row in conn.execute("SELECT account_id FROM journal_lines").fetchall()
                    }
                    self.assertEqual(linked_ids, {12, 13})
                    raise RuntimeError("rollback disposable schema")
            except RuntimeError as exc:
                self.assertEqual(str(exc), "rollback disposable schema")
        finally:
            conn.close()


if __name__ == "__main__":
    unittest.main()
