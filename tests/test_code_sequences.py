import sqlite3
import unittest

from code_sequences import next_code


class NumberSequenceTests(unittest.TestCase):
    def setUp(self):
        self.db = sqlite3.connect(":memory:", isolation_level=None)
        self.db.row_factory = sqlite3.Row
        self.db.execute("CREATE TABLE customers(id INTEGER PRIMARY KEY, code TEXT UNIQUE)")
        self.db.executemany("INSERT INTO customers(code) VALUES(?)", [("CUS-000004",), ("CUS-000009",)])

    def tearDown(self):
        self.db.close()

    def test_sequence_continues_after_existing_legacy_codes(self):
        code = next_code(self.db, "customer", "CUS", "customers", "code")
        self.assertEqual(code, "CUS-000010")
        self.db.execute("INSERT INTO customers(code) VALUES(?)", (code,))
        self.db.commit()
        self.assertEqual(next_code(self.db, "customer", "CUS", "customers", "code"), "CUS-000011")

    def test_sequences_are_independent(self):
        self.db.execute("CREATE TABLE suppliers(id INTEGER PRIMARY KEY, code TEXT UNIQUE)")
        self.assertEqual(next_code(self.db, "customer", "CUS", "customers", "code"), "CUS-000010")
        self.db.commit()
        self.assertEqual(next_code(self.db, "supplier", "SUP", "suppliers", "code"), "SUP-000001")

    def test_failed_insert_can_rollback_reserved_number(self):
        code = next_code(self.db, "customer", "CUS", "customers", "code")
        self.db.rollback()
        self.assertEqual(next_code(self.db, "customer", "CUS", "customers", "code"), code)


class PostgreSQLNumberSequenceTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        import os
        import uuid

        cls.dsn = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()
        if not cls.dsn:
            raise unittest.SkipTest("NEXUS_TEST_POSTGRES_DSN is not configured")
        from postgres_database import connect_postgres

        cls.connect_postgres = staticmethod(connect_postgres)
        cls.schema = "nexus_sequences_" + uuid.uuid4().hex
        connection = connect_postgres(cls.dsn)
        try:
            connection.execute(f'CREATE SCHEMA "{cls.schema}"')
            connection.execute(f'SET search_path TO "{cls.schema}"')
            connection.execute(
                "CREATE TABLE customers(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE)"
            )
            connection.execute(
                "CREATE TABLE document_sequences(sequence_key TEXT PRIMARY KEY, "
                "next_value INTEGER NOT NULL CHECK(next_value > 0))"
            )
            connection.execute(
                "INSERT INTO customers(code) VALUES(%s),(%s),(%s),(%s)",
                ("CUS-000004", "CUS-000009", "CON-000004", "CON-000009"),
            )
            connection.commit()
        finally:
            connection.close()

    @classmethod
    def tearDownClass(cls):
        if not getattr(cls, "dsn", ""):
            return
        connection = cls.connect_postgres(cls.dsn)
        try:
            connection.execute(f'DROP SCHEMA IF EXISTS "{cls.schema}" CASCADE')
            connection.commit()
        finally:
            connection.close()

    def test_sequence_continues_after_legacy_codes_and_rolls_back(self):
        from code_sequences import next_code

        connection = self.connect_postgres(self.dsn)
        try:
            connection.execute(f'SET search_path TO "{self.schema}"')
            code = next_code(connection, "customer", "CUS", "customers", "code")
            self.assertEqual(code, "CUS-000010")
            connection.execute("INSERT INTO customers(code) VALUES(%s)", (code,))
            connection.commit()
            self.assertEqual(
                next_code(connection, "customer", "CUS", "customers", "code"),
                "CUS-000011",
            )
            connection.rollback()
            self.assertEqual(
                next_code(connection, "customer", "CUS", "customers", "code"),
                "CUS-000011",
            )
            connection.rollback()
        finally:
            connection.close()

    def test_concurrent_first_reservations_are_unique(self):
        from concurrent.futures import ThreadPoolExecutor
        from threading import Barrier
        from code_sequences import next_code

        barrier = Barrier(2)

        def reserve_and_insert():
            connection = self.connect_postgres(self.dsn)
            try:
                connection.execute(f'SET search_path TO "{self.schema}"')
                barrier.wait(timeout=10)
                code = next_code(connection, "concurrent_customer", "CON", "customers", "code")
                connection.execute("INSERT INTO customers(code) VALUES(%s)", (code,))
                connection.commit()
                return code
            finally:
                connection.rollback()
                connection.close()

        with ThreadPoolExecutor(max_workers=2) as executor:
            codes = sorted(executor.map(lambda _: reserve_and_insert(), range(2)))

        self.assertEqual(codes, ["CON-000010", "CON-000011"])
        self.assertEqual(len(set(codes)), 2)
