"""Real PostgreSQL race test for cash-commitment overpayment protection.

Two independent Flask-style database connections attempt to pay the same
commitment concurrently. A row lock must serialize them so only one payment
can be accepted. The test owns and drops a unique disposable schema.
"""
import os
import unittest
import uuid
from concurrent.futures import ThreadPoolExecutor
from threading import Barrier

from postgres_database import connect_postgres

POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PostgreSQLCashCommitmentConcurrencyTests(unittest.TestCase):
    def test_concurrent_payments_cannot_overpay_one_commitment(self):
        from cash_commitments import (
            cash_commitment_payment_summary,
            initialize_cash_commitments_schema,
            record_cash_commitment_payment,
        )

        schema = "nexus_commitment_race_" + uuid.uuid4().hex[:14]
        admin = connect_postgres(
            POSTGRES_DSN, autocommit=True, schema="public",
            application_name="NEXUS cash commitment concurrency setup",
        )
        try:
            admin.execute(f'CREATE SCHEMA "{schema}"')
        finally:
            admin.close()

        try:
            setup = connect_postgres(
                POSTGRES_DSN, schema=schema,
                application_name="NEXUS cash commitment concurrency setup",
            )
            try:
                setup.execute("""
                    CREATE TABLE accounts(
                        id BIGINT PRIMARY KEY,
                        account_type TEXT NOT NULL,
                        is_group BIGINT NOT NULL DEFAULT 0,
                        active BIGINT NOT NULL DEFAULT 1
                    )
                """)
                setup.execute("""
                    CREATE TABLE journal_entries(
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        entry_date TEXT NOT NULL,
                        reference TEXT NOT NULL UNIQUE,
                        description TEXT NOT NULL,
                        status TEXT NOT NULL
                    )
                """)
                setup.execute("""
                    CREATE TABLE journal_lines(
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        entry_id BIGINT NOT NULL REFERENCES journal_entries(id),
                        account_id BIGINT NOT NULL REFERENCES accounts(id),
                        debit TEXT NOT NULL,
                        credit TEXT NOT NULL,
                        memo TEXT NOT NULL DEFAULT ''
                    )
                """)
                setup.execute(
                    "INSERT INTO accounts(id,account_type,is_group,active) VALUES"
                    "(2,'liability',0,1),(3,'asset',0,1)"
                )
                initialize_cash_commitments_schema(setup)
                commitment_id = setup.execute("""
                    INSERT INTO cash_commitments(
                        commitment_type,title,amount,due_date,payable_account_id,status
                    ) VALUES('recurring_expense','اختبار التزام متزامن','100.00',
                             '2026-11-30',2,'open')
                    RETURNING id
                """).fetchone()["id"]

                journal_ids = []
                for index in (1, 2):
                    entry_id = setup.execute("""
                        INSERT INTO journal_entries(entry_date,reference,description,status)
                        VALUES('2026-11-21',%s,%s,'posted') RETURNING id
                    """, (f"PG-COMMITMENT-PAY-{index}", "سداد اختبار متزامن")).fetchone()["id"]
                    setup.execute("""
                        INSERT INTO journal_lines(entry_id,account_id,debit,credit,memo)
                        VALUES(%s,2,'60.00','0','مدين الالتزام'),
                              (%s,3,'0','60.00','دائن النقدية')
                    """, (entry_id, entry_id))
                    journal_ids.append(int(entry_id))
                setup.commit()
            finally:
                setup.close()

            barrier = Barrier(2)

            def attempt_payment(index):
                connection = connect_postgres(
                    POSTGRES_DSN, schema=schema,
                    application_name=f"NEXUS commitment race worker {index}",
                )
                try:
                    barrier.wait(timeout=15)
                    try:
                        payment_id = record_cash_commitment_payment(
                            connection,
                            commitment_id,
                            "2026-11-21",
                            "60.00",
                            journal_ids[index],
                            reference=f"PG-COMMITMENT-ATTEMPT-{index}",
                            payable_account_id=2,
                        )
                        return ("posted", payment_id)
                    except ValueError as exc:
                        return ("rejected", str(exc))
                finally:
                    connection.close()

            with ThreadPoolExecutor(max_workers=2) as executor:
                outcomes = list(executor.map(attempt_payment, (0, 1)))

            self.assertEqual(
                sorted(outcome[0] for outcome in outcomes),
                ["posted", "rejected"],
                outcomes,
            )

            verify = connect_postgres(
                POSTGRES_DSN, schema=schema,
                application_name="NEXUS cash commitment concurrency verification",
            )
            try:
                summary = cash_commitment_payment_summary(verify, commitment_id)
                payment_count = verify.execute(
                    "SELECT COUNT(*) AS n FROM cash_commitment_payments WHERE commitment_id=%s",
                    (commitment_id,),
                ).fetchone()["n"]
                self.assertEqual(payment_count, 1)
                self.assertEqual(str(summary["paid_total"]), "60.00")
                self.assertEqual(summary["status"], "partially_paid")
            finally:
                verify.close()
        finally:
            cleanup = connect_postgres(
                POSTGRES_DSN, autocommit=True, schema="public",
                application_name="NEXUS cash commitment concurrency cleanup",
            )
            try:
                cleanup.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            finally:
                cleanup.close()


if __name__ == "__main__":
    unittest.main()
