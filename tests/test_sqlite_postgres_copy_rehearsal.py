"""End-to-end rehearsal of a read-only SQLite to isolated PostgreSQL copy.

Uses a tiny disposable accounting database and a unique PostgreSQL schema.
The production/company database is never opened by this test.
"""
import os
import sqlite3
import tempfile
import unittest
import uuid
from pathlib import Path

from postgres_database import connect_postgres
from scripts.copy_sqlite_to_postgres import copy_database
from scripts.verify_sqlite_postgres_copy import verify_copy


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class SQLitePostgreSQLCopyRehearsalTests(unittest.TestCase):
    def setUp(self):
        self.schema = "nexus_copy_rehearsal_" + uuid.uuid4().hex[:12]
        self.pg = connect_postgres(POSTGRES_DSN, autocommit=True)
        self.pg.execute(f'CREATE SCHEMA "{self.schema}"')
        self.pg.execute(f'''
            CREATE TABLE "{self.schema}".accounts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code TEXT NOT NULL
            );
            CREATE TABLE "{self.schema}".journal_entries (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entry_date TEXT NOT NULL
            );
            CREATE TABLE "{self.schema}".journal_lines (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entry_id BIGINT NOT NULL REFERENCES "{self.schema}".journal_entries(id),
                account_id BIGINT NOT NULL REFERENCES "{self.schema}".accounts(id),
                debit NUMERIC(24, 6) NOT NULL,
                credit NUMERIC(24, 6) NOT NULL
            );
        ''')
        self.temp_dir = tempfile.TemporaryDirectory(prefix="nexus-copy-rehearsal-")
        self.sqlite_path = str(Path(self.temp_dir.name) / "source.sqlite")
        source = sqlite3.connect(self.sqlite_path)
        try:
            source.execute("PRAGMA foreign_keys = ON")
            source.executescript("""
                CREATE TABLE accounts (
                    id INTEGER PRIMARY KEY,
                    code TEXT NOT NULL
                );
                CREATE TABLE journal_entries (
                    id INTEGER PRIMARY KEY,
                    entry_date TEXT NOT NULL
                );
                CREATE TABLE journal_lines (
                    id INTEGER PRIMARY KEY,
                    entry_id INTEGER NOT NULL REFERENCES journal_entries(id),
                    account_id INTEGER NOT NULL REFERENCES accounts(id),
                    debit NUMERIC NOT NULL,
                    credit NUMERIC NOT NULL
                );
                INSERT INTO accounts(id,code) VALUES (10,'1000'),(20,'2000');
                INSERT INTO journal_entries(id,entry_date)
                    VALUES (100,'2026-01-01'),(200,'2026-01-02');
                INSERT INTO journal_lines(id,entry_id,account_id,debit,credit)
                    VALUES
                    (1000,100,10,'125.10','0'),
                    (1001,100,20,'0','125.10'),
                    (2000,200,10,'50.00','0'),
                    (2001,200,20,'0','50.00');
            """)
            source.commit()
        finally:
            source.close()

    def tearDown(self):
        try:
            self.pg.execute(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')
        finally:
            self.pg.close()
            self.temp_dir.cleanup()

    def test_copy_and_financial_verification_preserve_all_rows_and_totals(self):
        result = copy_database(
            self.sqlite_path,
            POSTGRES_DSN,
            schema=self.schema,
            batch_size=2,
            apply=True,
        )
        self.assertTrue(result["committed"])
        self.assertTrue(result["source_read_only"])
        self.assertEqual(result["total_rows"], 8)
        self.assertEqual(
            result["table_row_counts"],
            {"accounts": 2, "journal_entries": 2, "journal_lines": 4},
        )

        report = verify_copy(self.sqlite_path, POSTGRES_DSN, schema=self.schema)
        self.assertTrue(report["passed"], report["issues"])
        self.assertEqual(report["issue_count"], 0)
        self.assertEqual(report["source_row_count"], 8)
        self.assertEqual(report["target_row_count"], 8)
        self.assertIn("journal_lines.debit_total", report["financial_and_inventory_controls"])
        self.assertIn("journal_lines.credit_total", report["financial_and_inventory_controls"])
        self.assertIn("journal_lines.debit_by_entry", report["financial_and_inventory_controls"])
        self.assertIn("journal_lines.credit_by_entry", report["financial_and_inventory_controls"])


if __name__ == "__main__":
    unittest.main()
