import os
import unittest
import uuid
from decimal import Decimal

try:
    import psycopg
except ImportError:
    psycopg = None

from activity_reporting import build_activity_performance_report
from company_activities import (
    enable_company_activity,
    initialize_company_activity_schema,
    resolve_activity_posting_account,
    set_activity_posting_account,
)


@unittest.skipUnless(
    os.environ.get("NEXUS_TEST_POSTGRES_DSN") and psycopg,
    "PostgreSQL integration DSN/driver is not configured",
)
class CompanyActivityPostgreSQLIntegrationTests(unittest.TestCase):
    def setUp(self):
        self.schema = "nexus_activity_" + uuid.uuid4().hex[:12]
        self.connection = psycopg.connect(
            os.environ["NEXUS_TEST_POSTGRES_DSN"],
            row_factory=psycopg.rows.dict_row,
        )
        self.connection.execute(f'CREATE SCHEMA "{self.schema}"')
        self.connection.execute(f'SET search_path TO "{self.schema}"')

    def tearDown(self):
        self.connection.rollback()
        self.connection.execute("SET search_path TO public")
        self.connection.execute(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')
        self.connection.commit()
        self.connection.close()

    def test_activity_registry_and_role_override_are_postgresql_compatible(self):
        self.connection.execute("""
            CREATE TABLE accounts(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code TEXT UNIQUE NOT NULL,
                account_type TEXT NOT NULL,
                is_group BOOLEAN NOT NULL DEFAULT FALSE,
                active BOOLEAN NOT NULL DEFAULT TRUE
            )
        """)
        self.connection.execute("""
            CREATE TABLE company_settings(
                setting_key TEXT PRIMARY KEY,
                setting_value TEXT
            )
        """)
        self.connection.execute(
            "INSERT INTO company_settings VALUES('activity','commercial')"
        )
        self.connection.execute(
            "INSERT INTO accounts(code,account_type) VALUES('4100','revenue')"
        )
        initialize_company_activity_schema(self.connection)
        enable_company_activity(self.connection, "service", primary=True)
        set_activity_posting_account(self.connection, "service", "revenue", "4100")
        self.assertEqual(
            resolve_activity_posting_account(self.connection, "revenue", "service"),
            "4100",
        )

    def test_activity_performance_report_groups_posted_documents(self):
        self.connection.execute("""
            CREATE TABLE company_settings(
                setting_key TEXT PRIMARY KEY,
                setting_value TEXT
            )
        """)
        self.connection.execute(
            "INSERT INTO company_settings VALUES('activity','commercial')"
        )
        self.connection.execute("""
            CREATE TABLE sales_invoices(
                id BIGINT PRIMARY KEY, activity_code TEXT, subtotal NUMERIC,
                tax_amount NUMERIC, total_amount NUMERIC, status TEXT,
                journal_entry_id BIGINT, cogs_journal_entry_id BIGINT
            )
        """)
        self.connection.execute("""
            CREATE TABLE supplier_bills(
                id BIGINT PRIMARY KEY, activity_code TEXT, subtotal NUMERIC,
                tax_amount NUMERIC, total_amount NUMERIC, status TEXT,
                journal_entry_id BIGINT
            )
        """)
        self.connection.execute("""
            CREATE TABLE goods_receipts(
                id BIGINT PRIMARY KEY, activity_code TEXT, total_value NUMERIC,
                status TEXT, journal_entry_id BIGINT
            )
        """)
        self.connection.execute("""
            CREATE TABLE stock_movements(
                id BIGINT PRIMARY KEY, activity_code TEXT, movement_type TEXT,
                total_cost NUMERIC, accounting_status TEXT, journal_entry_id BIGINT
            )
        """)
        self.connection.execute("""
            CREATE TABLE journal_lines(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                entry_id BIGINT, debit NUMERIC, credit NUMERIC
            )
        """)
        self.connection.execute(
            "INSERT INTO sales_invoices VALUES(1,'commercial',100,14,114,'posted',1,2)"
        )
        self.connection.execute(
            "INSERT INTO goods_receipts VALUES(1,'commercial',80,'posted',4)"
        )
        self.connection.execute(
            "INSERT INTO stock_movements VALUES(1,'commercial','receipt',80,'posted',4)"
        )
        self.connection.executemany(
            "INSERT INTO journal_lines(entry_id,debit,credit) VALUES(%s,%s,%s)",
            [(1,114,114),(2,25,25),(4,80,80)],
        )
        report = build_activity_performance_report(self.connection)
        self.assertEqual(report["journal_entry_count"], 3)
        self.assertEqual(report["activities"][0]["sales_total"], Decimal("114.00"))
        self.assertEqual(report["activities"][0]["stock_receipt_value"], Decimal("80.00"))
        self.assertEqual(report["unbalanced_journal_count"], 0)


if __name__ == "__main__":
    unittest.main()
