"""PostgreSQL integration coverage for effective-dated payroll compliance rules."""
import os
import unittest
import uuid
from decimal import Decimal

from postgres_database import connect_postgres
from payroll_compliance import ensure_default_payroll_rules, calculate_payroll_deductions


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class PostgreSQLPayrollComplianceTests(unittest.TestCase):
    def setUp(self):
        self.schema = "nexus_payroll_rules_" + uuid.uuid4().hex[:12]
        self.conn = connect_postgres(POSTGRES_DSN)
        self.conn.execute(f'CREATE SCHEMA "{self.schema}"')
        self.conn.execute(f'SET search_path TO "{self.schema}"')
        self.conn.execute("""
            CREATE TABLE company_settings(
                setting_key TEXT PRIMARY KEY, setting_value TEXT NOT NULL
            )
        """)
        self.conn.execute(
            "INSERT INTO company_settings(setting_key,setting_value) VALUES('tax_country','EG')"
        )
        self.conn.execute("""
            CREATE TABLE payroll_rule_sets(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                country_code TEXT NOT NULL, category_code TEXT NOT NULL,
                effective_from TEXT NOT NULL, personal_exemption_annual TEXT NOT NULL,
                taxable_rounding_unit TEXT NOT NULL DEFAULT '1',
                insurance_floor TEXT NOT NULL, insurance_ceiling TEXT NOT NULL,
                employee_insurance_rate TEXT NOT NULL, employer_insurance_rate TEXT NOT NULL,
                enabled BIGINT NOT NULL DEFAULT 1, notes TEXT NOT NULL DEFAULT '',
                UNIQUE(country_code,category_code,effective_from)
            )
        """)
        self.conn.execute("""
            CREATE TABLE payroll_tax_brackets(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                rule_set_id BIGINT NOT NULL, lower_bound TEXT NOT NULL,
                upper_bound TEXT, rate TEXT NOT NULL
            )
        """)
        self.conn.execute("""
            CREATE TABLE payroll_tax_tier_brackets(
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                rule_set_id BIGINT NOT NULL, income_max TEXT,
                lower_bound TEXT NOT NULL, upper_bound TEXT, rate TEXT NOT NULL
            )
        """)
        self.conn.commit()

    def tearDown(self):
        try:
            self.conn.rollback()
            self.conn.autocommit = True
            self.conn.execute(f'DROP SCHEMA IF EXISTS "{self.schema}" CASCADE')
        finally:
            self.conn.close()

    def test_egypt_2026_rules_seed_and_exact_deduction_calculation(self):
        self.assertEqual(ensure_default_payroll_rules(self.conn), "EG")
        row = self.conn.execute("""
            SELECT id,employee_insurance_rate,employer_insurance_rate
            FROM payroll_rule_sets
            WHERE country_code='EG' AND category_code='local'
              AND effective_from='2026-01-01'
        """).fetchone()
        self.assertIsNotNone(row)
        self.assertEqual(row["employee_insurance_rate"], "11")
        self.assertEqual(row["employer_insurance_rate"], "18.75")

        employee = {"legal_category": "local", "insured_wage": "0", "insurance_enabled": 1}
        result = calculate_payroll_deductions(
            self.conn, employee, Decimal("15000.00"), "2026-11"
        )
        self.assertEqual(result["insured_wage"], Decimal("15000.00"))
        self.assertEqual(result["employee_insurance"], Decimal("1650.00"))
        self.assertEqual(result["employer_insurance"], Decimal("2812.50"))
        self.assertEqual(result["tax"], Decimal("1482.50"))

    def test_default_seed_never_overwrites_reviewed_rule_values(self):
        ensure_default_payroll_rules(self.conn)
        self.conn.execute("""
            UPDATE payroll_rule_sets SET employee_insurance_rate='9.5'
            WHERE country_code='EG' AND category_code='local'
              AND effective_from='2026-01-01'
        """)
        self.conn.commit()
        self.assertEqual(ensure_default_payroll_rules(self.conn), "EG")
        rate = self.conn.execute("""
            SELECT employee_insurance_rate FROM payroll_rule_sets
            WHERE country_code='EG' AND category_code='local'
              AND effective_from='2026-01-01'
        """).fetchone()["employee_insurance_rate"]
        self.assertEqual(rate, "9.5")


if __name__ == "__main__":
    unittest.main()
