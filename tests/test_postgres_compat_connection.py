"""Tests for transparent SQL adaptation on application PostgreSQL connections."""
import unittest

from postgres_compat import PostgresCompatConnection


class FakeCursor:
    def __init__(self):
        self.calls = []

    def execute(self, query, params=None):
        self.calls.append(("execute", query, params))
        return self

    def executemany(self, query, params):
        self.calls.append(("executemany", query, list(params)))
        return self

    def fetchone(self):
        return ("ok",)


class FakeConnection:
    def __init__(self):
        self.calls = []
        self.last_cursor = None

    def execute(self, query, params=None):
        self.calls.append(("execute", query, params))
        return FakeCursor()

    def cursor(self, *args, **kwargs):
        self.last_cursor = FakeCursor()
        return self.last_cursor

    def commit(self):
        self.calls.append(("commit",))


class PostgresCompatConnectionTests(unittest.TestCase):
    def setUp(self):
        self.raw = FakeConnection()
        self.connection = PostgresCompatConnection(self.raw)

    def test_connection_execute_translates_qmark_parameters(self):
        self.connection.execute(
            "SELECT id FROM accounts WHERE code=? AND active=?",
            ("1100", 1),
        )
        self.assertEqual(
            self.raw.calls[-1],
            ("execute", "SELECT id FROM accounts WHERE code=%s AND active=%s", ("1100", 1)),
        )

    def test_connection_execute_preserves_native_format_placeholders(self):
        self.connection.execute("SELECT set_config('statement_timeout', %s, false)", ("2s",))
        self.assertEqual(
            self.raw.calls[-1],
            ("execute", "SELECT set_config('statement_timeout', %s, false)", ("2s",)),
        )

    def test_cursor_execute_and_executemany_are_adapted(self):
        cursor = self.connection.cursor()
        cursor.execute("SELECT value FROM settings WHERE key=?", ("base_currency",))
        cursor.executemany(
            "INSERT INTO settings(key, value) VALUES(?, ?)",
            [("a", "1"), ("b", "2")],
        )
        self.assertEqual(
            self.raw.last_cursor.calls,
            [
                ("execute", "SELECT value FROM settings WHERE key=%s", ("base_currency",)),
                ("executemany", "INSERT INTO settings(key, value) VALUES(%s, %s)", [("a", "1"), ("b", "2")]),
            ],
        )

    def test_create_table_sqlite_identity_and_text_timestamp_defaults_are_adapted(self):
        self.connection.execute("""
            CREATE TABLE probe (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)
        statement = self.raw.calls[-1][1]
        self.assertIn("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", statement)
        self.assertIn("DEFAULT (CURRENT_TIMESTAMP::text)", statement)

    def test_connection_methods_delegate_to_driver(self):
        self.connection.commit()
        self.assertEqual(self.raw.calls, [("commit",)])


if __name__ == "__main__":
    unittest.main()
