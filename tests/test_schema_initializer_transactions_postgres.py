"""PostgreSQL transaction tests for currency and fixed-asset schema setup."""
import os
import unittest
import uuid

import banking
import currency_center
import fixed_assets


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class SchemaInitializerCommitTests(unittest.TestCase):
    def _open_connection(self, schema):
        from postgres_database import connect_postgres

        connection = connect_postgres(
            POSTGRES_DSN, application_name="NEXUS schema initializer transaction test"
        )
        connection.execute(f'SET search_path TO "{schema}"')
        return connection

    def test_currency_schema_is_committed_before_connection_close(self):
        from postgres_database import connect_postgres

        schema = "nexus_currency_init_" + uuid.uuid4().hex
        admin = connect_postgres(POSTGRES_DSN)
        original_db = currency_center._db
        try:
            admin.execute(f'CREATE SCHEMA "{schema}"')
            admin.commit()
            setup = self._open_connection(schema)
            try:
                setup.execute("""
                    CREATE TABLE accounts (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                    )
                """)
                setup.commit()
            finally:
                setup.close()

            currency_center._db = lambda: self._open_connection(schema)
            currency_center.initialize_currency_schema()

            check = self._open_connection(schema)
            try:
                names = {
                    row["table_name"] for row in check.execute("""
                        SELECT table_name FROM information_schema.tables
                        WHERE table_schema=%s AND table_type='BASE TABLE'
                    """, (schema,)).fetchall()
                }
                self.assertTrue({
                    "fx_exchange_rates", "fx_transactions",
                    "fx_settlements", "fx_revaluations",
                }.issubset(names))
            finally:
                check.close()
        finally:
            currency_center._db = original_db
            admin.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            admin.commit()
            admin.close()


