"""Cross-database latest FX date lookup tests."""
import os
import sqlite3
import unittest

from currency_center import _latest_fx_date


class LatestFxDateSQLiteTests(unittest.TestCase):
    def setUp(self):
        self.conn = sqlite3.connect(":memory:")
        self.conn.row_factory = sqlite3.Row
        self.conn.executescript("""
            CREATE TABLE fx_settlements (
                id INTEGER PRIMARY KEY, transaction_id INTEGER NOT NULL,
                settlement_date TEXT NOT NULL
            );
            CREATE TABLE fx_revaluations (
                id INTEGER PRIMARY KEY, transaction_id INTEGER NOT NULL,
                revaluation_date TEXT NOT NULL
            );
        """)

    def tearDown(self):
        self.conn.close()

    def test_latest_settlement_and_revaluation_dates(self):
        self.conn.executemany(
            "INSERT INTO fx_settlements(transaction_id, settlement_date) VALUES(?, ?)",
            [(7, "2026-01-10"), (7, "2026-03-10"), (8, "2026-12-31")],
        )
        self.conn.executemany(
            "INSERT INTO fx_revaluations(transaction_id, revaluation_date) VALUES(?, ?)",
            [(7, "2026-02-28"), (7, "2026-04-30")],
        )
        self.assertEqual(_latest_fx_date(self.conn, "settlement", 7), "2026-03-10")
        self.assertEqual(_latest_fx_date(self.conn, "revaluation", 7), "2026-04-30")
        self.assertIsNone(_latest_fx_date(self.conn, "settlement", 99))

    def test_unknown_record_kind_is_rejected(self):
        with self.assertRaises(ValueError):
            _latest_fx_date(self.conn, "arbitrary_table", 7)


@unittest.skipUnless(
    os.environ.get("NEXUS_TEST_POSTGRES_DSN"),
    "PostgreSQL integration DSN not configured",
)
class LatestFxDatePostgreSQLTests(unittest.TestCase):
    def test_latest_dates_with_dict_rows_in_rolled_back_schema(self):
        import uuid
        import psycopg
        from psycopg.rows import dict_row

        schema = "nexus_fx_dates_" + uuid.uuid4().hex[:12]
        conn = psycopg.connect(
            os.environ["NEXUS_TEST_POSTGRES_DSN"], row_factory=dict_row
        )
        try:
            try:
                with conn.transaction():
                    conn.execute(f'CREATE SCHEMA "{schema}"')
                    conn.execute(f'SET LOCAL search_path TO "{schema}"')
                    conn.execute("""
                        CREATE TABLE fx_settlements (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            transaction_id BIGINT NOT NULL, settlement_date TEXT NOT NULL
                        )
                    """)
                    conn.execute("""
                        CREATE TABLE fx_revaluations (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            transaction_id BIGINT NOT NULL, revaluation_date TEXT NOT NULL
                        )
                    """)
                    conn.executemany(
                        "INSERT INTO fx_settlements(transaction_id, settlement_date) VALUES(%s, %s)",
                        [(7, "2026-01-10"), (7, "2026-03-10"), (8, "2026-12-31")],
                    )
                    conn.executemany(
                        "INSERT INTO fx_revaluations(transaction_id, revaluation_date) VALUES(%s, %s)",
                        [(7, "2026-02-28"), (7, "2026-04-30")],
                    )
                    self.assertEqual(_latest_fx_date(conn, "settlement", 7), "2026-03-10")
                    self.assertEqual(_latest_fx_date(conn, "revaluation", 7), "2026-04-30")
                    self.assertIsNone(_latest_fx_date(conn, "settlement", 99))
                    raise RuntimeError("rollback disposable schema")
            except RuntimeError as exc:
                self.assertEqual(str(exc), "rollback disposable schema")
        finally:
            conn.close()


if __name__ == "__main__":
    unittest.main()
