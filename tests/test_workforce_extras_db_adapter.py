"""Driver-level tests for the workforce extras SQL compatibility adapter."""
import os
import sqlite3
import unittest
import uuid

from workforce_extras import _execute
from db_compat import begin_write_transaction


class WorkforceExtrasSQLiteAdapterTests(unittest.TestCase):
    def test_qmark_queries_and_write_transaction(self):
        connection = sqlite3.connect(":memory:")
        try:
            self.assertTrue(begin_write_transaction(connection))
            _execute(connection, "CREATE TABLE workforce_adapter_probe (id INTEGER PRIMARY KEY, value TEXT)")
            _execute(connection, "INSERT INTO workforce_adapter_probe(value) VALUES (?)", ("kept",))
            self.assertEqual(
                _execute(connection, "SELECT value FROM workforce_adapter_probe WHERE id=?", (1,)).fetchone()[0],
                "kept",
            )
            connection.rollback()
            self.assertEqual(
                _execute(connection, "SELECT COUNT(*) FROM sqlite_master WHERE name='workforce_adapter_probe'").fetchone()[0],
                0,
            )
        finally:
            connection.close()


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class WorkforceExtrasPostgreSQLAdapterTests(unittest.TestCase):
    def test_workforce_extras_schema_migration_preserves_legacy_payroll(self):
        from postgres_database import connect_postgres
        import workforce_extras

        schema = "nexus_workforce_extras_" + uuid.uuid4().hex
        original_db = workforce_extras._db
        admin = connect_postgres(POSTGRES_DSN, application_name="NEXUS workforce extras schema test")
        try:
            admin.execute(f'CREATE SCHEMA "{schema}"')
            admin.commit()
            connection = connect_postgres(POSTGRES_DSN, application_name="NEXUS workforce extras schema test")
            connection.execute(f'SET search_path TO "{schema}"')
            connection.execute("""
                CREATE TABLE employees (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                )
            """)
            connection.execute("""
                CREATE TABLE payroll_runs (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    period TEXT NOT NULL, status TEXT NOT NULL
                )
            """)
            connection.execute("""
                CREATE TABLE payroll_lines (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    run_id BIGINT NOT NULL REFERENCES payroll_runs(id),
                    employee_id BIGINT NOT NULL REFERENCES employees(id),
                    basic_salary TEXT, allowances TEXT, incentives TEXT, overtime_amount TEXT,
                    absence_deduction TEXT, advance_deduction TEXT, other_deductions TEXT,
                    taxable_income_tax TEXT, employee_insurance TEXT, employer_insurance TEXT,
                    salary_raise TEXT
                )
            """)
            connection.execute("""
                CREATE TABLE payroll_payments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
                )
            """)
            connection.execute("""
                CREATE TABLE workforce_migrations (
                    migration_key TEXT PRIMARY KEY
                )
            """)
            connection.execute("INSERT INTO employees DEFAULT VALUES")
            connection.execute("INSERT INTO payroll_runs(period,status) VALUES('2026-10','posted')")
            connection.execute("""
                INSERT INTO payroll_lines(
                    run_id,employee_id,basic_salary,allowances,incentives,overtime_amount,
                    absence_deduction,advance_deduction,other_deductions,taxable_income_tax,
                    employee_insurance,employer_insurance,salary_raise
                ) VALUES(1,1,'10000','500','0','0','0','0','100','250','1000','1500','200')
            """)
            connection.commit()
            connection.close()

            def open_schema_connection():
                conn = connect_postgres(POSTGRES_DSN, application_name="NEXUS workforce extras schema test")
                conn.execute(f'SET search_path TO "{schema}"')
                return conn

            workforce_extras._db = open_schema_connection
            workforce_extras.initialize_workforce_extras_schema()

            check = open_schema_connection()
            first_count = check.execute(
                "SELECT COUNT(*) AS count FROM payroll_line_items WHERE source_type='legacy_aggregate'"
            ).fetchone()["count"]
            raise_amount = check.execute("""
                SELECT amount FROM payroll_line_items
                WHERE payroll_line_id=1 AND item_name='العلاوة المطبقة (بيان تاريخي)'
            """).fetchone()["amount"]
            check.close()
            self.assertGreater(first_count, 0)
            self.assertEqual(raise_amount, "200.00")

            workforce_extras.initialize_workforce_extras_schema()
            check = open_schema_connection()
            second_count = check.execute(
                "SELECT COUNT(*) AS count FROM payroll_line_items WHERE source_type='legacy_aggregate'"
            ).fetchone()["count"]
            migration_count = check.execute("""
                SELECT COUNT(*) AS count FROM workforce_migrations
                WHERE migration_key='payroll_line_items_legacy_snapshot_v1'
            """).fetchone()["count"]
            check.close()
            self.assertEqual(second_count, first_count)
            self.assertEqual(migration_count, 1)
        finally:
            workforce_extras._db = original_db
            admin.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
            admin.commit()
            admin.close()

    def test_qmark_queries_and_write_transaction(self):
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN, application_name="NEXUS workforce extras adapter test")
        try:
            self.assertTrue(begin_write_transaction(connection))
            _execute(
                connection,
                "CREATE TEMP TABLE workforce_adapter_probe "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value TEXT)",
            )
            _execute(connection, "INSERT INTO workforce_adapter_probe(value) VALUES (?)", ("kept",))
            row = _execute(
                connection,
                "SELECT value FROM workforce_adapter_probe WHERE id=?",
                (1,),
            ).fetchone()
            self.assertEqual(row["value"], "kept")
            connection.rollback()
        finally:
            connection.close()


if __name__ == "__main__":
    unittest.main()
