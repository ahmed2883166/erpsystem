"""Driver-level tests for the workforce extras SQL compatibility adapter."""
import os
import sqlite3
import unittest

from workforce_extras import _execute
from db_compat import begin_write_transaction


class WorkforceExtrasSQLiteAdapterTests(unittest.TestCase):
    def test_qmark_queries_and_write_transaction(self):
        connection = sqlite3.connect(":memory:")
        try:
            self.assertTrue(begin_write_transaction(connection))
            _execute(connection, "CREATE TABLE workforce_adapter_probe (id INTEGER PRIMARY KEY, value TEXT)")
            _execute(connection, "INSERT INTO workforce_adapter_probe(value) VALUES (?)", ("kept",))
            self.assertEqual(
                _execute(connection, "SELECT value FROM workforce_adapter_probe WHERE id=?", (1,)).fetchone()[0],
                "kept",
            )
            connection.rollback()
            self.assertEqual(
                _execute(connection, "SELECT COUNT(*) FROM sqlite_master WHERE name='workforce_adapter_probe'").fetchone()[0],
                0,
            )
        finally:
            connection.close()


POSTGRES_DSN = os.environ.get("NEXUS_TEST_POSTGRES_DSN", "").strip()


@unittest.skipUnless(POSTGRES_DSN, "NEXUS_TEST_POSTGRES_DSN is not configured")
class WorkforceExtrasPostgreSQLAdapterTests(unittest.TestCase):
    def test_qmark_queries_and_write_transaction(self):
        from postgres_database import connect_postgres

        connection = connect_postgres(POSTGRES_DSN, application_name="NEXUS workforce extras adapter test")
        try:
            self.assertTrue(begin_write_transaction(connection))
            _execute(
                connection,
                "CREATE TEMP TABLE workforce_adapter_probe "
                "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value TEXT)",
            )
            _execute(connection, "INSERT INTO workforce_adapter_probe(value) VALUES (?)", ("kept",))
            row = _execute(
                connection,
                "SELECT value FROM workforce_adapter_probe WHERE id=?",
                (1,),
            ).fetchone()
            self.assertEqual(row["value"], "kept")
            connection.rollback()
        finally:
            connection.close()


if __name__ == "__main__":
    unittest.main()
