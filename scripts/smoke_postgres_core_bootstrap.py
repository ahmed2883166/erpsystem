"""Isolated PostgreSQL smoke test through the Flask database factory.

Creates a uniquely named schema, initializes the real foundational schema,
posts a balanced journal through accounting_core.post_journal, verifies
idempotency, and drops the schema. No SQLite database or public schema is used.
"""
import os
import re
import sys
import tempfile
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from flask import Flask

from accounting_core import post_journal
from core_schema import initialize_core_schema
from database import connect_database, register_database_connection_teardown
from management_dashboard import initialize_management_dashboard_schema
from postgres_audit_schema import initialize_postgres_audit_schema
from stock import _install_stock_location_triggers


def main():
    dsn = os.environ.get("NEXUS_POSTGRES_DSN", "").strip()
    if not dsn:
        raise SystemExit("NEXUS_POSTGRES_DSN is required.")
    if not os.environ.get("NEXUS_DB_BACKEND") == "postgresql":
        raise SystemExit("NEXUS_DB_BACKEND=postgresql is required.")

    schema = "admrail_smoke_" + uuid.uuid4().hex[:16]
    if not re.fullmatch(r"[a-z][a-z0-9_]{0,62}", schema):
        raise RuntimeError("Generated unsafe schema name.")

    flask_app = Flask("admrail-postgres-smoke")
    register_database_connection_teardown(flask_app)

    with flask_app.app_context():
        sqlite_fallback_path = Path(tempfile.gettempdir()) / (
            "admrail-postgres-must-not-fallback-" + uuid.uuid4().hex + ".db"
        )
        connection = connect_database(
            str(sqlite_fallback_path), isolation_level="", decimal_aggregates=False
        )
        if sqlite_fallback_path.exists():
            raise AssertionError("PostgreSQL selection unexpectedly created a SQLite file.")
        if connection.info.transaction_status.name != "IDLE":
            raise AssertionError("Database factory returned an active PostgreSQL transaction.")
        created = False
        try:
            connection.execute(f'CREATE SCHEMA "{schema}"')
            created = True
            connection.execute(f'SET search_path TO "{schema}"')
            initialize_core_schema(connection)
            initialize_postgres_audit_schema(connection)
            initialize_management_dashboard_schema(connection, "commercial")
            connection.execute("""
                CREATE TABLE stock_locations (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    warehouse_id INTEGER NOT NULL,
                    active INTEGER NOT NULL DEFAULT 1
                )
            """)
            connection.execute("""
                CREATE TABLE stock_product_locations (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    warehouse_id INTEGER NOT NULL,
                    location_id INTEGER NOT NULL
                )
            """)
            _install_stock_location_triggers(connection)
            connection.commit()

            connection.execute(
                "INSERT INTO company_settings(setting_key, setting_value) VALUES (%s, %s)",
                ("company_name", "ADMRAIL PostgreSQL Smoke"),
            )
            cash_id = connection.execute(
                """INSERT INTO accounts(code, name_ar, account_type, is_group, active)
                   VALUES (%s, %s, %s, %s, %s) RETURNING id""",
                ("1000", "الصندوق - اختبار", "asset", 0, 1),
            ).fetchone()["id"]
            capital_id = connection.execute(
                """INSERT INTO accounts(code, name_ar, account_type, is_group, active)
                   VALUES (%s, %s, %s, %s, %s) RETURNING id""",
                ("3000", "رأس المال - اختبار", "equity", 0, 1),
            ).fetchone()["id"]

            lines = [
                (cash_id, "100.00", "0", "مدين"),
                (capital_id, "0", "100.00", "دائن"),
            ]
            entry_id = post_journal(
                connection, "2026-01-01", "PG-SMOKE-001",
                "اختبار ترحيل قيد PostgreSQL", lines,
            )
            repeated_entry_id = post_journal(
                connection, "2026-01-01", "PG-SMOKE-001",
                "اختبار ترحيل قيد PostgreSQL", lines,
            )
            if repeated_entry_id != entry_id:
                raise AssertionError("Journal posting is not idempotent.")

            totals = connection.execute(
                """SELECT SUM(debit::numeric) AS debit_total,
                          SUM(credit::numeric) AS credit_total
                   FROM journal_lines WHERE entry_id = %s""",
                (entry_id,),
            ).fetchone()
            posted = connection.execute(
                "SELECT status FROM journal_entries WHERE id = %s", (entry_id,)
            ).fetchone()
            debit = totals["debit_total"]
            credit = totals["credit_total"]
            if not posted or posted["status"] != "posted":
                raise AssertionError("Journal posting did not persist posted status.")
            if debit != credit or debit != 100:
                raise AssertionError(f"Unbalanced smoke journal: debit={debit}, credit={credit}")

            version = connection.execute(
                "SELECT version FROM management_dashboard_data_version WHERE id=1"
            ).fetchone()["version"]
            if version < 1:
                raise AssertionError("PostgreSQL dashboard invalidation triggers did not run.")

            audit_id = connection.execute(
                "INSERT INTO audit_log(action,created_at) VALUES (%s,%s) RETURNING id",
                ("postgres-smoke", "2026-01-01T00:00:00"),
            ).fetchone()["id"]
            connection.execute("SAVEPOINT audit_update_guard")
            try:
                connection.execute(
                    "UPDATE audit_log SET details=%s WHERE id=%s",
                    ("must be rejected", audit_id),
                )
            except Exception:
                connection.execute("ROLLBACK TO SAVEPOINT audit_update_guard")
                connection.execute("RELEASE SAVEPOINT audit_update_guard")
            else:
                raise AssertionError("PostgreSQL audit log allowed an UPDATE.")

            connection.execute(
                "INSERT INTO stock_locations(id,warehouse_id,active) VALUES (1,7,1)"
            )
            connection.execute("SAVEPOINT stock_location_guard")
            try:
                connection.execute(
                    "INSERT INTO stock_product_locations(id,warehouse_id,location_id) VALUES (1,8,1)"
                )
            except Exception:
                connection.execute("ROLLBACK TO SAVEPOINT stock_location_guard")
                connection.execute("RELEASE SAVEPOINT stock_location_guard")
            else:
                raise AssertionError("Stock location trigger allowed a cross-warehouse default.")
            connection.execute(
                "INSERT INTO stock_product_locations(id,warehouse_id,location_id) VALUES (2,7,1)"
            )
            connection.execute("SAVEPOINT stock_deactivation_guard")
            try:
                connection.execute("UPDATE stock_locations SET active=0 WHERE id=1")
            except Exception:
                connection.execute("ROLLBACK TO SAVEPOINT stock_deactivation_guard")
                connection.execute("RELEASE SAVEPOINT stock_deactivation_guard")
            else:
                raise AssertionError("Stock location trigger allowed deactivation of a default location.")

            connection.commit()
            print(
                "POSTGRES_CORE_BOOTSTRAP=PASS "
                f"schema={schema} tables=10 journal_entry={entry_id} "
                f"idempotent=yes debit={debit} credit={credit} dashboard_version={version} audit_guard=PASS stock_guards=PASS"
            )
            return 0
        except Exception:
            connection.rollback()
            raise
        finally:
            if created:
                try:
                    connection.execute("SET search_path TO public")
                    connection.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
                    connection.commit()
                except Exception:
                    connection.rollback()
            connection.close()


if __name__ == "__main__":
    sys.exit(main())
