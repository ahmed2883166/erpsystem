-- PostgreSQL-native core schema. Amounts and exchange rates use exact NUMERIC.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL,
    must_change_password INTEGER NOT NULL DEFAULT 0,
    permissions_json TEXT
);

CREATE TABLE IF NOT EXISTS accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    name_ar TEXT NOT NULL,
    account_type TEXT NOT NULL,
    parent_id BIGINT REFERENCES accounts(id),
    is_group INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS journal_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_date TEXT NOT NULL,
    reference TEXT,
    description TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'posted',
    created_by BIGINT REFERENCES users(id),
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS journal_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id BIGINT NOT NULL REFERENCES journal_entries(id) ON DELETE CASCADE,
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    debit NUMERIC(24, 6) NOT NULL DEFAULT 0,
    credit NUMERIC(24, 6) NOT NULL DEFAULT 0,
    memo TEXT,
    CONSTRAINT ck_journal_lines_nonnegative_amounts
        CHECK (debit >= 0 AND credit >= 0),
    CONSTRAINT ck_journal_lines_single_sided
        CHECK (debit = 0 OR credit = 0)
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    action TEXT NOT NULL,
    details TEXT,
    created_at TEXT NOT NULL,
    entity_type TEXT,
    entity_id TEXT,
    remote_addr TEXT,
    outcome TEXT NOT NULL DEFAULT 'success',
    actor_name TEXT,
    before_values TEXT,
    after_values TEXT,
    submitted_values TEXT,
    reason TEXT,
    request_id TEXT
);

CREATE TABLE IF NOT EXISTS company_settings (
    setting_key TEXT PRIMARY KEY,
    setting_value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS currencies (
    code TEXT PRIMARY KEY,
    name_ar TEXT NOT NULL,
    symbol TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 0,
    is_base INTEGER NOT NULL DEFAULT 0,
    rate_to_base NUMERIC(24, 10) NOT NULL DEFAULT 0,
    updated_at TEXT
);

CREATE TABLE IF NOT EXISTS tax_rates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    name_ar TEXT NOT NULL,
    rate NUMERIC(9, 6) NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    remote_addr TEXT NOT NULL,
    attempted_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS accounting_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_name TEXT NOT NULL,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    locked INTEGER NOT NULL DEFAULT 0,
    created_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_journal_lines_entry ON journal_lines(entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_account_entry ON journal_lines(account_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_entry_account ON journal_lines(entry_id, account_id);
CREATE INDEX IF NOT EXISTS idx_journal_entries_entry_date ON journal_entries(entry_date, id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON audit_log(created_at, id);
CREATE INDEX IF NOT EXISTS idx_login_attempts_username_time ON login_attempts(username, attempted_at);
