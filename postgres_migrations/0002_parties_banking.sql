-- Commercial party master data and independent cash/bank ledgers.
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    tax_number TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    credit_limit NUMERIC(24, 6) NOT NULL DEFAULT 0,
    discount_type TEXT NOT NULL DEFAULT 'none',
    discount_value NUMERIC(24, 6) NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    tax_number TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS salespersons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cash_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind TEXT NOT NULL CHECK(kind IN ('cash','bank')),
    name_ar TEXT NOT NULL,
    account_id BIGINT NOT NULL UNIQUE REFERENCES accounts(id),
    branch_id BIGINT,
    currency_code TEXT NOT NULL DEFAULT 'EGP' REFERENCES currencies(code),
    bank_name TEXT NOT NULL DEFAULT '',
    iban TEXT NOT NULL DEFAULT '',
    active INTEGER NOT NULL DEFAULT 1,
    opening_date TEXT NOT NULL,
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cash_accounts_kind_active
    ON cash_accounts(kind,active);

CREATE TABLE IF NOT EXISTS bank_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_no TEXT NOT NULL UNIQUE,
    transaction_date TEXT NOT NULL,
    bank_account_id BIGINT NOT NULL REFERENCES accounts(id),
    transaction_type TEXT NOT NULL CHECK(transaction_type IN ('deposit','withdrawal','transfer','fee')),
    amount NUMERIC(24, 6) NOT NULL CHECK(amount > 0),
    counter_account_id BIGINT REFERENCES accounts(id),
    destination_bank_account_id BIGINT REFERENCES accounts(id),
    description TEXT NOT NULL,
    bank_reference TEXT NOT NULL DEFAULT '',
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    reconciled INTEGER NOT NULL DEFAULT 0,
    statement_date TEXT,
    statement_reference TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_bank_transfer_destination CHECK (
        transaction_type <> 'transfer' OR
        (destination_bank_account_id IS NOT NULL AND destination_bank_account_id <> bank_account_id)
    )
);
CREATE INDEX IF NOT EXISTS idx_bank_tx_date
    ON bank_transactions(transaction_date,bank_account_id);

CREATE TABLE IF NOT EXISTS bank_statement_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_account_id BIGINT NOT NULL REFERENCES accounts(id),
    statement_date TEXT NOT NULL,
    signed_amount NUMERIC(24, 6) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    bank_reference TEXT NOT NULL DEFAULT '',
    matched_transaction_id BIGINT REFERENCES bank_transactions(id),
    matched_journal_line_id BIGINT REFERENCES journal_lines(id),
    matched_side TEXT CHECK(matched_side IN ('source','destination')),
    matched_at TIMESTAMPTZ,
    matched_by BIGINT REFERENCES users(id),
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_bank_statement_account_date
    ON bank_statement_lines(bank_account_id,statement_date,id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_bank_statement_tx_side
    ON bank_statement_lines(matched_transaction_id,matched_side)
    WHERE matched_transaction_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_bank_statement_journal_line
    ON bank_statement_lines(matched_journal_line_id)
    WHERE matched_journal_line_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS bank_statement_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_account_id BIGINT NOT NULL REFERENCES accounts(id),
    period_start TEXT NOT NULL,
    period_end TEXT NOT NULL,
    opening_balance NUMERIC(24, 6) NOT NULL,
    closing_balance NUMERIC(24, 6) NOT NULL,
    created_by BIGINT REFERENCES users(id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    opening_reviewed INTEGER NOT NULL DEFAULT 0,
    opening_review_note TEXT NOT NULL DEFAULT '',
    CONSTRAINT ck_bank_statement_period CHECK(period_end >= period_start),
    UNIQUE(bank_account_id,period_start,period_end)
);
