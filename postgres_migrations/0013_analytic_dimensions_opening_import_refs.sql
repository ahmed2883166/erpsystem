-- Additive accounting dimensions and opening-balance import idempotency.
-- Existing journal rows remain valid because all dimension references are nullable.

CREATE TABLE IF NOT EXISTS branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name_ar TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    address TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    tax_number TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS cost_centers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name_ar TEXT NOT NULL,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name_ar TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active',
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE journal_lines
    ADD COLUMN IF NOT EXISTS branch_id BIGINT REFERENCES branches(id),
    ADD COLUMN IF NOT EXISTS cost_center_id BIGINT REFERENCES cost_centers(id),
    ADD COLUMN IF NOT EXISTS project_id BIGINT REFERENCES projects(id),
    ADD COLUMN IF NOT EXISTS stock_product_id BIGINT REFERENCES stock_products(id),
    ADD COLUMN IF NOT EXISTS stock_warehouse_id BIGINT REFERENCES stock_warehouses(id),
    ADD COLUMN IF NOT EXISTS customer_id BIGINT REFERENCES customers(id),
    ADD COLUMN IF NOT EXISTS salesperson_id BIGINT REFERENCES salespersons(id),
    ADD COLUMN IF NOT EXISTS supplier_id BIGINT REFERENCES suppliers(id);

CREATE INDEX IF NOT EXISTS idx_journal_lines_branch
    ON journal_lines(branch_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_cost_center
    ON journal_lines(cost_center_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_project
    ON journal_lines(project_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_stock_product
    ON journal_lines(stock_product_id, account_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_stock_warehouse
    ON journal_lines(stock_warehouse_id, account_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_customer
    ON journal_lines(customer_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_salesperson
    ON journal_lines(salesperson_id, entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_lines_supplier
    ON journal_lines(supplier_id, entry_id);

CREATE TABLE IF NOT EXISTS opening_balance_import_refs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_type TEXT NOT NULL,
    reference TEXT NOT NULL,
    entity_key TEXT NOT NULL,
    journal_entry_id BIGINT NOT NULL REFERENCES journal_entries(id),
    source_file TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_opening_balance_import_ref
        UNIQUE (record_type, reference, entity_key)
);

CREATE INDEX IF NOT EXISTS idx_opening_balance_import_journal
    ON opening_balance_import_refs(journal_entry_id);
