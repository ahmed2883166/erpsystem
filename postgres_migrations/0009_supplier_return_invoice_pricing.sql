-- Preserve the original supplier invoice pricing for each returned quantity.
-- Stock movements continue to use FIFO/average carrying cost; the difference is posted
-- to product COGS so supplier balances, input VAT and inventory valuation reconcile.
ALTER TABLE supplier_credit_note_lines
    ADD COLUMN IF NOT EXISTS supplier_total NUMERIC(24, 8);

CREATE TABLE IF NOT EXISTS supplier_credit_note_bill_line_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_line_id BIGINT NOT NULL
        REFERENCES supplier_credit_note_lines(id) ON DELETE CASCADE,
    supplier_bill_line_id BIGINT NOT NULL
        REFERENCES supplier_bill_inventory_lines(id),
    quantity NUMERIC(24, 8) NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(24, 8) NOT NULL CHECK (unit_price >= 0),
    total_value NUMERIC(24, 8) NOT NULL CHECK (total_value >= 0)
);

CREATE INDEX IF NOT EXISTS idx_supplier_credit_bill_line
    ON supplier_credit_note_bill_line_allocations(supplier_bill_line_id);

CREATE INDEX IF NOT EXISTS idx_supplier_credit_bill_note_line
    ON supplier_credit_note_bill_line_allocations(credit_note_line_id);
