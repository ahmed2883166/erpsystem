-- PostgreSQL-native purchasing workflow. Exact quantities and values use NUMERIC.
CREATE TABLE IF NOT EXISTS purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_no TEXT NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    order_date DATE NOT NULL,
    expected_date DATE,
    status TEXT NOT NULL DEFAULT 'draft',
    notes TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_by BIGINT REFERENCES users(id),
    submitted_at TIMESTAMPTZ,
    approved_by BIGINT REFERENCES users(id),
    approved_at TIMESTAMPTZ,
    rejected_by BIGINT REFERENCES users(id),
    rejected_at TIMESTAMPTZ,
    rejection_reason TEXT,
    approval_reason TEXT
);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_approval
    ON purchase_orders(status,created_at,id);

CREATE TABLE IF NOT EXISTS purchase_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no TEXT NOT NULL UNIQUE,
    request_date DATE NOT NULL,
    required_date DATE,
    department TEXT NOT NULL DEFAULT '',
    purpose TEXT NOT NULL,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    estimated_unit_price NUMERIC(24,8) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'draft',
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_by BIGINT REFERENCES users(id),
    submitted_at TIMESTAMPTZ,
    approved_by BIGINT REFERENCES users(id),
    approved_at TIMESTAMPTZ,
    approval_reason TEXT,
    rejected_by BIGINT REFERENCES users(id),
    rejected_at TIMESTAMPTZ,
    rejection_reason TEXT,
    converted_to_po_id BIGINT REFERENCES purchase_orders(id),
    converted_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_purchase_requests_status_date
    ON purchase_requests(status,request_date,id);
CREATE INDEX IF NOT EXISTS idx_purchase_requests_creator
    ON purchase_requests(created_by,status,id);

CREATE TABLE IF NOT EXISTS purchase_order_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    unit_price NUMERIC(24,8) NOT NULL CHECK(unit_price >= 0),
    received_qty NUMERIC(24,8) NOT NULL DEFAULT 0 CHECK(received_qty >= 0),
    entered_quantity NUMERIC(24,8),
    uom_id BIGINT REFERENCES stock_uoms(id),
    uom_key TEXT,
    entered_uom_name TEXT,
    conversion_factor NUMERIC(24,10) NOT NULL DEFAULT 1 CHECK(conversion_factor > 0)
);

CREATE TABLE IF NOT EXISTS goods_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no TEXT NOT NULL UNIQUE,
    po_id BIGINT REFERENCES purchase_orders(id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    warehouse_id BIGINT NOT NULL REFERENCES stock_warehouses(id),
    receipt_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'posted',
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    total_value NUMERIC(24,8) NOT NULL DEFAULT 0,
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    branch_id BIGINT,
    cost_center_id BIGINT,
    project_id BIGINT
);
CREATE INDEX IF NOT EXISTS idx_purchase_receipts_supplier
    ON goods_receipts(supplier_id,receipt_date);

CREATE TABLE IF NOT EXISTS goods_receipt_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT NOT NULL REFERENCES goods_receipts(id) ON DELETE CASCADE,
    po_line_id BIGINT REFERENCES purchase_order_lines(id),
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    unit_cost NUMERIC(24,8) NOT NULL CHECK(unit_cost >= 0),
    total_cost NUMERIC(24,8) NOT NULL CHECK(total_cost >= 0),
    entered_quantity NUMERIC(24,8),
    uom_id BIGINT REFERENCES stock_uoms(id),
    uom_key TEXT,
    entered_uom_name TEXT,
    conversion_factor NUMERIC(24,10) NOT NULL DEFAULT 1 CHECK(conversion_factor > 0),
    location_id BIGINT REFERENCES stock_locations(id)
);

CREATE TABLE IF NOT EXISTS supplier_bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_no TEXT NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    bill_date DATE NOT NULL,
    due_date DATE,
    supplier_invoice_no TEXT NOT NULL,
    subtotal NUMERIC(24,8) NOT NULL,
    tax_rate NUMERIC(9,6) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    total_amount NUMERIC(24,8) NOT NULL,
    paid_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    credited_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'posted',
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    input_vat_deductible_percent NUMERIC(9,6) NOT NULL DEFAULT 100,
    asset_code TEXT,
    asset_name TEXT,
    asset_category TEXT,
    asset_ready_date DATE,
    asset_residual_value NUMERIC(24,8) NOT NULL DEFAULT 0,
    asset_useful_life_months INTEGER,
    asset_depreciation_method TEXT NOT NULL DEFAULT 'straight_line',
    asset_annual_rate NUMERIC(9,6) NOT NULL DEFAULT 0,
    asset_account_id BIGINT REFERENCES accounts(id),
    asset_accum_account_id BIGINT REFERENCES accounts(id),
    asset_expense_account_id BIGINT REFERENCES accounts(id),
    bill_kind TEXT NOT NULL DEFAULT 'inventory',
    expense_account_id BIGINT REFERENCES accounts(id),
    submitted_by BIGINT REFERENCES users(id),
    submitted_at TIMESTAMPTZ,
    approved_by BIGINT REFERENCES users(id),
    approved_at TIMESTAMPTZ,
    rejected_by BIGINT REFERENCES users(id),
    rejected_at TIMESTAMPTZ,
    rejection_reason TEXT,
    approval_reason TEXT,
    branch_id BIGINT,
    cost_center_id BIGINT,
    project_id BIGINT,
    CHECK(input_vat_deductible_percent BETWEEN 0 AND 100),
    CHECK(credited_amount >= 0 AND paid_amount >= 0)
);
CREATE INDEX IF NOT EXISTS idx_purchase_bills_supplier
    ON supplier_bills(supplier_id,bill_date);
CREATE INDEX IF NOT EXISTS idx_supplier_bill_invoice_lookup
    ON supplier_bills(supplier_id,supplier_invoice_no);
CREATE INDEX IF NOT EXISTS idx_supplier_bills_approval
    ON supplier_bills(status,bill_date,id);

CREATE TABLE IF NOT EXISTS supplier_bill_receipts (
    bill_id BIGINT NOT NULL REFERENCES supplier_bills(id) ON DELETE CASCADE,
    receipt_id BIGINT NOT NULL REFERENCES goods_receipts(id),
    matched_amount NUMERIC(24,8) NOT NULL CHECK(matched_amount >= 0),
    PRIMARY KEY(bill_id,receipt_id)
);
CREATE INDEX IF NOT EXISTS idx_supplier_bill_receipt_lookup
    ON supplier_bill_receipts(receipt_id);

CREATE TABLE IF NOT EXISTS supplier_bill_inventory_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES supplier_bills(id) ON DELETE CASCADE,
    line_no INTEGER NOT NULL,
    receipt_line_id BIGINT NOT NULL REFERENCES goods_receipt_lines(id),
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    billed_quantity NUMERIC(24,8) NOT NULL CHECK(billed_quantity > 0),
    invoice_unit_price NUMERIC(24,8) NOT NULL CHECK(invoice_unit_price >= 0),
    line_total NUMERIC(24,8) NOT NULL CHECK(line_total >= 0),
    UNIQUE(bill_id,line_no)
);
CREATE INDEX IF NOT EXISTS idx_supplier_bill_inventory_receipt_line
    ON supplier_bill_inventory_lines(receipt_line_id);

CREATE TABLE IF NOT EXISTS supplier_bill_asset_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES supplier_bills(id) ON DELETE CASCADE,
    line_no INTEGER NOT NULL,
    asset_code TEXT NOT NULL,
    asset_name TEXT NOT NULL,
    asset_category TEXT NOT NULL DEFAULT '',
    cost NUMERIC(24,8) NOT NULL CHECK(cost >= 0),
    ready_date DATE NOT NULL,
    residual_value NUMERIC(24,8) NOT NULL DEFAULT 0,
    useful_life_months INTEGER NOT NULL CHECK(useful_life_months > 0),
    depreciation_method TEXT NOT NULL DEFAULT 'straight_line',
    annual_rate NUMERIC(9,6) NOT NULL DEFAULT 0,
    asset_account_id BIGINT NOT NULL REFERENCES accounts(id),
    accum_account_id BIGINT NOT NULL REFERENCES accounts(id),
    expense_account_id BIGINT NOT NULL REFERENCES accounts(id),
    UNIQUE(bill_id,line_no),
    UNIQUE(bill_id,asset_code),
    CHECK(residual_value >= 0 AND residual_value <= cost)
);
CREATE INDEX IF NOT EXISTS idx_supplier_bill_asset_lines
    ON supplier_bill_asset_lines(bill_id,line_no);

CREATE TABLE IF NOT EXISTS supplier_credit_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_no TEXT NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    bill_id BIGINT NOT NULL REFERENCES supplier_bills(id),
    credit_date DATE NOT NULL,
    supplier_credit_no TEXT NOT NULL,
    reason TEXT NOT NULL,
    subtotal NUMERIC(24,8) NOT NULL,
    tax_rate NUMERIC(9,6) NOT NULL,
    tax_amount NUMERIC(24,8) NOT NULL,
    total_amount NUMERIC(24,8) NOT NULL,
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    status TEXT NOT NULL DEFAULT 'posted',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancel_journal_entry_id BIGINT REFERENCES journal_entries(id),
    cancelled_by BIGINT REFERENCES users(id),
    cancelled_at TIMESTAMPTZ,
    cancellation_reason TEXT,
    UNIQUE(supplier_id,supplier_credit_no)
);
CREATE TABLE IF NOT EXISTS supplier_credit_note_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_id BIGINT NOT NULL REFERENCES supplier_credit_notes(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    warehouse_id BIGINT NOT NULL REFERENCES stock_warehouses(id),
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    unit_cost NUMERIC(24,8) NOT NULL CHECK(unit_cost >= 0),
    total_cost NUMERIC(24,8) NOT NULL CHECK(total_cost >= 0),
    entered_quantity NUMERIC(24,8),
    uom_id BIGINT REFERENCES stock_uoms(id),
    uom_key TEXT,
    entered_uom_name TEXT,
    conversion_factor NUMERIC(24,10) NOT NULL DEFAULT 1 CHECK(conversion_factor > 0)
);
CREATE TABLE IF NOT EXISTS supplier_credit_note_layer_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_line_id BIGINT NOT NULL REFERENCES supplier_credit_note_lines(id) ON DELETE CASCADE,
    stock_movement_id BIGINT NOT NULL REFERENCES stock_movements(id),
    source_layer_id BIGINT NOT NULL REFERENCES stock_valuation_layers(id),
    lot_id BIGINT REFERENCES stock_lots(id),
    location_id BIGINT REFERENCES stock_locations(id),
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    unit_cost NUMERIC(24,8) NOT NULL CHECK(unit_cost >= 0),
    total_cost NUMERIC(24,8) NOT NULL CHECK(total_cost >= 0)
);
CREATE INDEX IF NOT EXISTS idx_supplier_credit_layer_line
    ON supplier_credit_note_layer_allocations(credit_note_line_id);

CREATE TABLE IF NOT EXISTS supplier_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_no TEXT NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    payment_date DATE NOT NULL,
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    cash_account_id BIGINT NOT NULL REFERENCES accounts(id),
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    reference TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS supplier_payment_allocations (
    payment_id BIGINT NOT NULL REFERENCES supplier_payments(id),
    bill_id BIGINT NOT NULL REFERENCES supplier_bills(id),
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    PRIMARY KEY(payment_id,bill_id)
);
