-- PostgreSQL-native inventory schema. Quantities and valuation use exact NUMERIC.
CREATE TABLE IF NOT EXISTS stock_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_ar TEXT NOT NULL UNIQUE,
    code TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL DEFAULT '',
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS stock_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    name_ar TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT '',
    category_id BIGINT REFERENCES stock_categories(id),
    product_type TEXT NOT NULL DEFAULT 'goods',
    uom TEXT NOT NULL DEFAULT 'قطعة',
    base_uom_id BIGINT,
    barcode TEXT UNIQUE,
    track_lot INTEGER NOT NULL DEFAULT 0,
    track_expiry INTEGER NOT NULL DEFAULT 0,
    min_qty NUMERIC(24, 8) NOT NULL DEFAULT 0,
    purchase_price NUMERIC(24, 8) NOT NULL DEFAULT 0,
    sale_price NUMERIC(24, 8) NOT NULL DEFAULT 0,
    reorder_point NUMERIC(24, 8) NOT NULL DEFAULT 0,
    reorder_qty NUMERIC(24, 8) NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS stock_warehouses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name_ar TEXT NOT NULL,
    branch TEXT NOT NULL DEFAULT '',
    branch_id BIGINT,
    active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS stock_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL REFERENCES stock_warehouses(id),
    parent_id BIGINT,
    code TEXT NOT NULL,
    name_ar TEXT NOT NULL,
    location_type TEXT NOT NULL CHECK(location_type IN ('floor','zone','rack','bin')),
    active INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(warehouse_id,parent_id,code),
    UNIQUE(id,warehouse_id),
    CONSTRAINT fk_stock_location_parent_same_warehouse
        FOREIGN KEY(parent_id,warehouse_id) REFERENCES stock_locations(id,warehouse_id)
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE IF NOT EXISTS stock_product_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    warehouse_id BIGINT NOT NULL REFERENCES stock_warehouses(id),
    location_id BIGINT NOT NULL,
    is_default INTEGER NOT NULL DEFAULT 1,
    UNIQUE(product_id,warehouse_id),
    FOREIGN KEY(location_id,warehouse_id) REFERENCES stock_locations(id,warehouse_id)
);

CREATE TABLE IF NOT EXISTS stock_lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    lot_number TEXT NOT NULL,
    production_date DATE,
    expiry_date DATE,
    UNIQUE(product_id,lot_number),
    CHECK(expiry_date IS NULL OR production_date IS NULL OR expiry_date >= production_date)
);

CREATE TABLE IF NOT EXISTS stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_no TEXT NOT NULL UNIQUE,
    movement_type TEXT NOT NULL,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    source_warehouse_id BIGINT REFERENCES stock_warehouses(id),
    target_warehouse_id BIGINT REFERENCES stock_warehouses(id),
    source_location_id BIGINT REFERENCES stock_locations(id),
    target_location_id BIGINT REFERENCES stock_locations(id),
    lot_id BIGINT REFERENCES stock_lots(id),
    quantity NUMERIC(24, 8) NOT NULL CHECK(quantity > 0),
    unit_cost NUMERIC(24, 8) NOT NULL DEFAULT 0,
    total_cost NUMERIC(24, 8) NOT NULL DEFAULT 0,
    movement_date DATE NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    journal_entry_id BIGINT REFERENCES journal_entries(id),
    accounting_status TEXT NOT NULL DEFAULT 'pending',
    accounting_note TEXT,
    issue_purpose TEXT,
    entered_quantity NUMERIC(24, 8),
    entered_uom_id BIGINT,
    entered_uom_key TEXT,
    entered_uom_name TEXT,
    CHECK(source_warehouse_id IS NULL OR target_warehouse_id IS NULL
          OR source_warehouse_id <> target_warehouse_id)
);
CREATE INDEX IF NOT EXISTS idx_stock_moves_product_date
    ON stock_movements(product_id,movement_date,id);
CREATE INDEX IF NOT EXISTS idx_stock_movement_journal
    ON stock_movements(journal_entry_id) WHERE journal_entry_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS stock_valuation_layers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    warehouse_id BIGINT NOT NULL REFERENCES stock_warehouses(id),
    location_id BIGINT REFERENCES stock_locations(id),
    lot_id BIGINT REFERENCES stock_lots(id),
    source_movement_id BIGINT NOT NULL REFERENCES stock_movements(id),
    qty_in NUMERIC(24, 8) NOT NULL,
    qty_remaining NUMERIC(24, 8) NOT NULL,
    unit_cost NUMERIC(24, 8) NOT NULL,
    value_remaining NUMERIC(24, 8) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK(qty_in >= 0 AND qty_remaining >= 0 AND qty_remaining <= qty_in)
);
CREATE INDEX IF NOT EXISTS idx_stock_layers_product_wh
    ON stock_valuation_layers(product_id,warehouse_id,id);
CREATE INDEX IF NOT EXISTS idx_stock_layers_location
    ON stock_valuation_layers(location_id,product_id);

CREATE TABLE IF NOT EXISTS stock_warehouse_product_settings (
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    warehouse_id BIGINT NOT NULL REFERENCES stock_warehouses(id),
    min_qty NUMERIC(24, 8) NOT NULL DEFAULT 0,
    reorder_point NUMERIC(24, 8) NOT NULL DEFAULT 0,
    reorder_qty NUMERIC(24, 8) NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY(product_id,warehouse_id),
    CHECK(min_qty >= 0 AND reorder_point >= 0 AND reorder_qty >= 0)
);
CREATE INDEX IF NOT EXISTS idx_stock_wh_product_reorder
    ON stock_warehouse_product_settings(warehouse_id,reorder_point,product_id);

CREATE TABLE IF NOT EXISTS stocktakes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    count_no TEXT NOT NULL UNIQUE,
    warehouse_id BIGINT NOT NULL REFERENCES stock_warehouses(id),
    count_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft',
    notes TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    approved_by BIGINT REFERENCES users(id),
    approved_at TIMESTAMPTZ,
    journal_entry_id BIGINT REFERENCES journal_entries(id),
    movement_cutoff_id BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS stocktake_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_id BIGINT NOT NULL REFERENCES stocktakes(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    location_id BIGINT REFERENCES stock_locations(id),
    lot_id BIGINT REFERENCES stock_lots(id),
    snapshot_qty NUMERIC(24, 8) NOT NULL,
    counted_qty NUMERIC(24, 8),
    variance_qty NUMERIC(24, 8),
    counted_unit_cost NUMERIC(24, 8) NOT NULL DEFAULT 0,
    variance_value NUMERIC(24, 8) NOT NULL DEFAULT 0,
    notes TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_stocktake_lines_header
    ON stocktake_lines(stocktake_id,product_id,location_id,lot_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_stocktake_line_scope
    ON stocktake_lines(stocktake_id,product_id,COALESCE(location_id,0),COALESCE(lot_id,0));

CREATE TABLE IF NOT EXISTS stock_uom_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE,
    name_ar TEXT NOT NULL UNIQUE,
    active INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS stock_uoms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES stock_uom_categories(id),
    code TEXT NOT NULL UNIQUE,
    name_ar TEXT NOT NULL,
    factor_to_base NUMERIC(24, 10) NOT NULL CHECK(factor_to_base > 0),
    is_base INTEGER NOT NULL DEFAULT 0,
    active INTEGER NOT NULL DEFAULT 1,
    UNIQUE(category_id,name_ar)
);
ALTER TABLE stock_products
    ADD CONSTRAINT fk_stock_product_base_uom
    FOREIGN KEY(base_uom_id) REFERENCES stock_uoms(id);

CREATE TABLE IF NOT EXISTS stock_product_uoms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES stock_products(id),
    uom_id BIGINT REFERENCES stock_uoms(id),
    custom_code TEXT NOT NULL,
    custom_name TEXT NOT NULL,
    factor_to_base NUMERIC(24, 10) NOT NULL CHECK(factor_to_base > 0),
    is_base INTEGER NOT NULL DEFAULT 0,
    purchase_enabled INTEGER NOT NULL DEFAULT 1,
    sales_enabled INTEGER NOT NULL DEFAULT 1,
    active INTEGER NOT NULL DEFAULT 1,
    UNIQUE(product_id,custom_code),
    UNIQUE(product_id,uom_id)
);
CREATE INDEX IF NOT EXISTS idx_stock_product_uoms_product
    ON stock_product_uoms(product_id,active);

