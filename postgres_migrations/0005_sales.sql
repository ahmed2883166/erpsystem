-- PostgreSQL-native sales workflow. Monetary and quantity columns remain exact NUMERIC.
CREATE TABLE IF NOT EXISTS sales_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    invoice_date DATE NOT NULL,
    due_date DATE,
    warehouse_id BIGINT REFERENCES stock_warehouses(id),
    subtotal NUMERIC(24,8) NOT NULL,
    tax_rate NUMERIC(9,6) NOT NULL DEFAULT 0,
    tax_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    discount_type TEXT NOT NULL DEFAULT 'none',
    discount_value NUMERIC(24,8) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    total_amount NUMERIC(24,8) NOT NULL,
    paid_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    credited_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'posted',
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    cogs_journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    created_by BIGINT REFERENCES users(id),
    sales_channel TEXT NOT NULL DEFAULT 'default',
    revenue_account_code TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sales_order_id BIGINT,
    branch_id BIGINT,
    cost_center_id BIGINT,
    project_id BIGINT,
    salesperson_id BIGINT REFERENCES salespersons(id),
    CHECK(subtotal >= 0 AND tax_amount >= 0 AND discount_amount >= 0),
    CHECK(total_amount >= 0 AND paid_amount >= 0 AND credited_amount >= 0),
    CHECK(discount_amount <= subtotal)
);
CREATE INDEX IF NOT EXISTS idx_sales_invoice_customer
    ON sales_invoices(customer_id,invoice_date);
CREATE INDEX IF NOT EXISTS idx_sales_invoices_order
    ON sales_invoices(sales_order_id,id);

CREATE TABLE IF NOT EXISTS sales_invoice_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES sales_invoices(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES stock_products(id),
    description TEXT NOT NULL,
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    unit_price NUMERIC(24,8) NOT NULL CHECK(unit_price >= 0),
    line_total NUMERIC(24,8) NOT NULL CHECK(line_total >= 0),
    cost_total NUMERIC(24,8) NOT NULL DEFAULT 0 CHECK(cost_total >= 0),
    stock_movement_id BIGINT REFERENCES stock_movements(id),
    entered_quantity NUMERIC(24,8),
    uom_id BIGINT REFERENCES stock_uoms(id),
    uom_key TEXT,
    entered_uom_name TEXT,
    conversion_factor NUMERIC(24,10) NOT NULL DEFAULT 1 CHECK(conversion_factor > 0),
    tax_rate NUMERIC(9,6) NOT NULL DEFAULT 0,
    tax_treatment TEXT NOT NULL DEFAULT 'standard',
    tax_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    sales_order_line_id BIGINT
);
CREATE INDEX IF NOT EXISTS idx_sales_invoice_lines_order_line
    ON sales_invoice_lines(sales_order_line_id,invoice_id);

CREATE TABLE IF NOT EXISTS sales_invoice_line_lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id BIGINT NOT NULL REFERENCES sales_invoice_lines(id) ON DELETE CASCADE,
    lot_id BIGINT REFERENCES stock_lots(id),
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    cost_total NUMERIC(24,8) NOT NULL DEFAULT 0 CHECK(cost_total >= 0)
);

CREATE TABLE IF NOT EXISTS customer_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no TEXT NOT NULL UNIQUE,
    invoice_id BIGINT NOT NULL REFERENCES sales_invoices(id),
    receipt_date DATE NOT NULL,
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    cash_account_id BIGINT NOT NULL REFERENCES accounts(id),
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    reference TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sales_receipts_invoice
    ON customer_receipts(invoice_id,receipt_date);

CREATE TABLE IF NOT EXISTS customer_receipt_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    receipt_date DATE NOT NULL,
    total_amount NUMERIC(24,8) NOT NULL CHECK(total_amount > 0),
    cash_account_id BIGINT NOT NULL REFERENCES accounts(id),
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    reference TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS customer_receipt_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES customer_receipt_batches(id) ON DELETE CASCADE,
    invoice_id BIGINT NOT NULL REFERENCES sales_invoices(id),
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    UNIQUE(batch_id,invoice_id)
);
CREATE INDEX IF NOT EXISTS idx_customer_receipt_alloc_invoice
    ON customer_receipt_allocations(invoice_id);

CREATE TABLE IF NOT EXISTS customer_advance_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    receipt_date DATE NOT NULL,
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    cash_account_id BIGINT NOT NULL REFERENCES accounts(id),
    journal_entry_id BIGINT NOT NULL UNIQUE REFERENCES journal_entries(id),
    reference TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS customer_advance_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advance_receipt_id BIGINT NOT NULL REFERENCES customer_advance_receipts(id),
    invoice_id BIGINT NOT NULL REFERENCES sales_invoices(id),
    allocation_date DATE NOT NULL,
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    journal_entry_id BIGINT NOT NULL UNIQUE REFERENCES journal_entries(id),
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_customer_advance_alloc_receipt
    ON customer_advance_allocations(advance_receipt_id,allocation_date,id);
CREATE INDEX IF NOT EXISTS idx_customer_advance_alloc_invoice
    ON customer_advance_allocations(invoice_id);

CREATE TABLE IF NOT EXISTS customer_advance_refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_no TEXT NOT NULL UNIQUE,
    advance_receipt_id BIGINT NOT NULL REFERENCES customer_advance_receipts(id),
    refund_date DATE NOT NULL,
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    cash_account_id BIGINT NOT NULL REFERENCES accounts(id),
    journal_entry_id BIGINT NOT NULL UNIQUE REFERENCES journal_entries(id),
    reference TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS customer_advance_reversals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type TEXT NOT NULL CHECK(source_type IN ('receipt','allocation','refund')),
    source_id BIGINT NOT NULL,
    original_journal_entry_id BIGINT NOT NULL UNIQUE REFERENCES journal_entries(id),
    reversal_journal_entry_id BIGINT NOT NULL UNIQUE REFERENCES journal_entries(id),
    reversal_date DATE NOT NULL,
    reason TEXT NOT NULL,
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(source_type,source_id)
);
CREATE INDEX IF NOT EXISTS idx_customer_advance_reversals_date
    ON customer_advance_reversals(reversal_date,source_type);

CREATE TABLE IF NOT EXISTS sales_credit_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_no TEXT NOT NULL UNIQUE,
    invoice_id BIGINT NOT NULL REFERENCES sales_invoices(id),
    credit_date DATE NOT NULL,
    reason TEXT NOT NULL,
    subtotal NUMERIC(24,8) NOT NULL,
    tax_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    total_amount NUMERIC(24,8) NOT NULL,
    journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    cogs_journal_entry_id BIGINT UNIQUE REFERENCES journal_entries(id),
    status TEXT NOT NULL DEFAULT 'posted',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    refundable_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    cancel_journal_entry_id BIGINT REFERENCES journal_entries(id),
    cancel_cogs_journal_entry_id BIGINT REFERENCES journal_entries(id),
    cancelled_by BIGINT REFERENCES users(id),
    cancelled_at TIMESTAMPTZ,
    cancellation_reason TEXT
);
CREATE INDEX IF NOT EXISTS idx_sales_credit_invoice
    ON sales_credit_notes(invoice_id,credit_date,id);

CREATE TABLE IF NOT EXISTS sales_credit_note_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_id BIGINT NOT NULL REFERENCES sales_credit_notes(id) ON DELETE CASCADE,
    invoice_line_id BIGINT NOT NULL REFERENCES sales_invoice_lines(id),
    product_id BIGINT REFERENCES stock_products(id),
    description TEXT NOT NULL,
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    unit_price NUMERIC(24,8) NOT NULL CHECK(unit_price >= 0),
    line_total NUMERIC(24,8) NOT NULL CHECK(line_total >= 0),
    tax_rate NUMERIC(9,6) NOT NULL DEFAULT 0,
    tax_treatment TEXT NOT NULL DEFAULT 'standard',
    tax_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    cost_total NUMERIC(24,8) NOT NULL DEFAULT 0,
    stock_movement_id BIGINT REFERENCES stock_movements(id),
    entered_quantity NUMERIC(24,8),
    uom_id BIGINT REFERENCES stock_uoms(id),
    uom_key TEXT,
    entered_uom_name TEXT,
    conversion_factor NUMERIC(24,10) NOT NULL DEFAULT 1 CHECK(conversion_factor > 0)
);
CREATE TABLE IF NOT EXISTS sales_credit_note_line_lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credit_note_line_id BIGINT NOT NULL REFERENCES sales_credit_note_lines(id) ON DELETE CASCADE,
    lot_id BIGINT REFERENCES stock_lots(id),
    quantity NUMERIC(24,8) NOT NULL CHECK(quantity > 0),
    stock_movement_id BIGINT REFERENCES stock_movements(id)
);

CREATE TABLE IF NOT EXISTS customer_refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_no TEXT NOT NULL UNIQUE,
    credit_note_id BIGINT NOT NULL REFERENCES sales_credit_notes(id),
    refund_date DATE NOT NULL,
    amount NUMERIC(24,8) NOT NULL CHECK(amount > 0),
    cash_account_id BIGINT NOT NULL REFERENCES accounts(id),
    journal_entry_id BIGINT NOT NULL UNIQUE REFERENCES journal_entries(id),
    reference TEXT NOT NULL DEFAULT '',
    created_by BIGINT REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sales_discount_approval_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    gross_subtotal NUMERIC(24,8) NOT NULL,
    discount_amount NUMERIC(24,8) NOT NULL,
    discount_percent NUMERIC(9,6) NOT NULL,
    payload_json TEXT NOT NULL,
    created_by BIGINT REFERENCES users(id),
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
    reviewed_by BIGINT REFERENCES users(id),
    reviewed_at TIMESTAMPTZ,
    decision_reason TEXT NOT NULL DEFAULT '',
    invoice_id BIGINT REFERENCES sales_invoices(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    request_type TEXT NOT NULL DEFAULT 'invoice',
    sales_order_id BIGINT
);
CREATE INDEX IF NOT EXISTS idx_sales_discount_approval_status
    ON sales_discount_approval_requests(status,created_at,id);
CREATE INDEX IF NOT EXISTS idx_sales_discount_order
    ON sales_discount_approval_requests(sales_order_id,status);

CREATE TABLE IF NOT EXISTS sales_invoice_workflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_no TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    gross_subtotal NUMERIC(24,8) NOT NULL,
    discount_amount NUMERIC(24,8) NOT NULL DEFAULT 0,
    discount_percent NUMERIC(9,6) NOT NULL DEFAULT 0,
    payload_json TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft'
        CHECK(status IN ('draft','pending_approval','approved','rejected','cancelled','posted')),
    created_by BIGINT REFERENCES users(id),
    submitted_by BIGINT REFERENCES users(id),
    submitted_at TIMESTAMPTZ,
    approved_by BIGINT REFERENCES users(id),
    approved_at TIMESTAMPTZ,
    approved_credit_override INTEGER NOT NULL DEFAULT 0,
    rejected_by BIGINT REFERENCES users(id),
    rejected_at TIMESTAMPTZ,
    rejection_reason TEXT NOT NULL DEFAULT '',
    cancelled_by BIGINT REFERENCES users(id),
    cancelled_at TIMESTAMPTZ,
    cancellation_reason TEXT NOT NULL DEFAULT '',
    posted_invoice_id BIGINT UNIQUE REFERENCES sales_invoices(id),
    posted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by BIGINT REFERENCES users(id),
    last_edit_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_sales_invoice_workflows_status
    ON sales_invoice_workflows(status,created_at,id);
CREATE INDEX IF NOT EXISTS idx_sales_invoice_workflows_customer
    ON sales_invoice_workflows(customer_id,invoice_date,id);
